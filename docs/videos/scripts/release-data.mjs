// Builds src/releases/<tag>.json from the GitHub release notes: tag, date, previous tag, stats, and
// every pull request classified by type, then regenerates src/releases/index.ts so the release shows
// up as a composition. Highlights are editorial: the script keeps any already in the file and leaves
// an empty list for a new release.
//
//   node scripts/release-data.mjs v4.5.76
import {execFileSync} from 'node:child_process';
import {existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync} from 'node:fs';

const tag = process.argv[2];
if (!/^v\d+\.\d+\.\d+$/.test(tag ?? '')) {
	console.error('usage: node scripts/release-data.mjs vX.Y.Z');
	process.exit(1);
}

const release = JSON.parse(
	execFileSync('gh', ['release', 'view', tag, '--repo', 'ccxt/ccxt', '--json', 'tagName,publishedAt,body,url'], {encoding: 'utf8'}),
);
const exchangeIds = new Set(JSON.parse(readFileSync(new URL('../../../exchanges.json', import.meta.url), 'utf8')).ids);

// conventional-commit type -> the buckets shown in the video
const TYPE_KIND = {
	feat: 'feat', feature: 'feat',
	fix: 'fix', bugfix: 'fix', hotfix: 'fix',
	perf: 'perf',
	test: 'test', tests: 'test',
	docs: 'docs', doc: 'docs',
	refactor: 'chore', chore: 'chore', ci: 'chore', build: 'chore', revert: 'chore', style: 'chore',
};

// titles without a conventional type ("BTSE integration", "bitget parseUtaBalance fix")
const classifyText = (text) => {
	if (/^revert\b/i.test(text)) {
		return 'chore';
	}
	if (/\b(fix|fixes|fixed|bug)\b/i.test(text)) {
		return 'fix';
	}
	if (/\b(add|adds|added|integration|support)\b/i.test(text)) {
		return 'feat';
	}
	return 'chore';
};

const parseEntry = (line) => {
	const title = line.slice(2).replace(/ by @\S+ in https:\S+$/, '');
	const conventional = title.match(/^([\w-]+)!?(?:\(([^)]*)\))?!?:\s*(.+)$/);
	if (conventional !== null && TYPE_KIND[conventional[1].toLowerCase()] !== undefined) {
		return {kind: TYPE_KIND[conventional[1].toLowerCase()], scope: conventional[2] ?? null, text: conventional[3]};
	}
	if (conventional !== null && conventional[2] === undefined) {
		// "bingx: fix websocket balance routing" — the prefix is a scope, not a type
		return {kind: classifyText(conventional[3]), scope: conventional[1], text: conventional[3]};
	}
	return {kind: classifyText(title), scope: null, text: title};
};

const [changedSection, newSection = ''] = release.body.split('## New Contributors');
const entries = changedSection.split('\n').filter((line) => line.startsWith('* '));

const authors = new Set();
const exchanges = new Set();
const changes = [];
for (const line of entries) {
	const author = line.match(/ by @(\S+) in https:/)?.[1];
	if (author !== undefined && !author.endsWith('[bot]')) {
		authors.add(author);
	}
	const {kind, scope, text} = parseEntry(line);
	// a scope is authoritative; only unscoped titles are scanned for exchange ids,
	// so verbs like "derive" in "fix(btse): derive ticker percentage" are not counted
	const candidates = scope !== null ? scope.split(/[,\s]+/) : text.toLowerCase().split(/[^a-z0-9]+/);
	for (const candidate of candidates) {
		if (exchangeIds.has(candidate)) {
			exchanges.add(candidate);
		}
	}
	changes.push({pr: Number(line.match(/\/pull\/(\d+)\s*$/)?.[1]), kind, scope, title: text});
}

const newContributors = newSection
	.split('\n')
	.filter((line) => line.startsWith('* '))
	.map((line) => line.match(/@(\S+) made/)?.[1])
	.filter((handle) => handle !== undefined);

const releasesDir = new URL('../src/releases/', import.meta.url);
const out = new URL(`${tag}.json`, releasesDir);
const existing = existsSync(out) ? JSON.parse(readFileSync(out, 'utf8')) : {};
const data = {
	tag,
	previous: release.body.match(/compare\/(v[\d.]+)\.\.\./)?.[1] ?? null,
	date: release.publishedAt.slice(0, 10),
	url: release.url,
	stats: {
		prs: entries.length,
		exchanges: exchanges.size,
		contributors: authors.size,
		newContributors,
	},
	highlights: existing.highlights ?? [],
	changes,
};

mkdirSync(releasesDir, {recursive: true});
writeFileSync(out, JSON.stringify(data, null, 2) + '\n');

// src/releases/index.ts lists every release file, newest first
const versionKey = (name) => name.slice(1, -'.json'.length).split('.').map(Number);
const tags = readdirSync(releasesDir)
	.filter((name) => /^v\d+\.\d+\.\d+\.json$/.test(name))
	.sort((a, b) => {
		const [x, y] = [versionKey(a), versionKey(b)];
		return y[0] - x[0] || y[1] - x[1] || y[2] - x[2];
	})
	.map((name) => name.slice(0, -'.json'.length));
const ident = (t) => t.split('.').join('_');
const index = [
	'// Generated by scripts/release-data.mjs — one entry per src/releases/<tag>.json, newest first.',
	'import type { Release } from "../release/types";',
	...tags.map((t) => `import ${ident(t)} from "./${t}.json";`),
	'',
	'export const RELEASES: Release[] = [',
	...tags.map((t) => `  ${ident(t)} as Release,`),
	'];',
	'',
].join('\n');
writeFileSync(new URL('index.ts', releasesDir), index);

const byKind = {};
for (const change of changes) {
	byKind[change.kind] = (byKind[change.kind] ?? 0) + 1;
}
console.log(`wrote src/releases/${tag}.json`, data.stats, byKind, `exchanges: ${[...exchanges].sort().join(', ')}`);
if (data.highlights.length === 0) {
	console.log(`next: add 1-4 highlights to src/releases/${tag}.json, then npm run release:render -- ${tag}`);
}
