export type Visual =
  | { type: "command"; text: string }
  | { type: "metrics"; items: { value: string; label: string }[] }
  | { type: "chips"; items: string[] }
  | { type: "code"; lines: string[] };

export type HighlightKind = "feat" | "perf" | "fix" | "core";

export type Highlight = {
  kind: HighlightKind;
  title: string;
  detail: string;
  prs: number[];
  visual: Visual;
};

// Buckets for the full change list (scripts/release-data.mjs maps commit types onto these).
export type ChangeKind = "feat" | "fix" | "perf" | "test" | "docs" | "chore";

export type Change = {
  pr: number;
  kind: ChangeKind;
  scope: string | null;
  title: string;
};

// Shape of src/releases/<tag>.json, generated by scripts/release-data.mjs (highlights hand-curated).
export type Release = {
  tag: string;
  previous: string;
  date: string;
  url: string;
  stats: {
    prs: number;
    exchanges: number;
    contributors: number;
    newContributors: string[];
  };
  highlights: Highlight[];
  changes: Change[];
};
