        await this.loadMarkets ();
        symbols = this.marketSymbols (symbols, undefined, false, true, true);
        let messageHash = 'positions';
        if ((symbols !== undefined) && !this.isEmpty (symbols)) {
            messageHash += '::' + symbols.join (',');
        }
