using Test
using Ccxt
function testDecimalToPrecision()

    exchange = get(ccxt, Symbol("Exchange"), nothing)(Dict{Symbol, Any}(
        Symbol("id") => "regirock"
    ));
    @test decimalToPrecision(exchange, "12.3456000", TRUNCATE, 100, DECIMAL_PLACES) == "12.3456";
    @test decimalToPrecision(exchange, "12.3456", TRUNCATE, 100, DECIMAL_PLACES) == "12.3456";
    @test decimalToPrecision(exchange, "12.3456", TRUNCATE, 4, DECIMAL_PLACES) == "12.3456";
    @test decimalToPrecision(exchange, "12.3456", TRUNCATE, 3, DECIMAL_PLACES) == "12.345";
    @test decimalToPrecision(exchange, "12.3456", TRUNCATE, 2, DECIMAL_PLACES) == "12.34";
    @test decimalToPrecision(exchange, "12.3456", TRUNCATE, 1, DECIMAL_PLACES) == "12.3";
    @test decimalToPrecision(exchange, "12.3456", TRUNCATE, 0, DECIMAL_PLACES) == "12";
    @test decimalToPrecision(exchange, "0.0000001", TRUNCATE, 8, DECIMAL_PLACES) == "0.0000001";
    @test decimalToPrecision(exchange, "0.00000001", TRUNCATE, 8, DECIMAL_PLACES) == "0.00000001";
    @test decimalToPrecision(exchange, "0.000000000", TRUNCATE, 9, DECIMAL_PLACES, PAD_WITH_ZERO) == "0.000000000";
    @test decimalToPrecision(exchange, "0.000000001", TRUNCATE, 9, DECIMAL_PLACES, PAD_WITH_ZERO) == "0.000000001";
    @test decimalToPrecision(exchange, "12.3456", TRUNCATE, -1, DECIMAL_PLACES) == "10";
    @test decimalToPrecision(exchange, "123.456", TRUNCATE, -1, DECIMAL_PLACES) == "120";
    @test decimalToPrecision(exchange, "123.456", TRUNCATE, -2, DECIMAL_PLACES) == "100";
    @test decimalToPrecision(exchange, "9.99999", TRUNCATE, -1, DECIMAL_PLACES) == "0";
    @test decimalToPrecision(exchange, "99.9999", TRUNCATE, -1, DECIMAL_PLACES) == "90";
    @test decimalToPrecision(exchange, "99.9999", TRUNCATE, -2, DECIMAL_PLACES) == "0";
    @test decimalToPrecision(exchange, "0", TRUNCATE, 0, DECIMAL_PLACES) == "0";
    @test decimalToPrecision(exchange, "-0.9", TRUNCATE, 0, DECIMAL_PLACES) == "0";
    @test decimalToPrecision(exchange, "0.000123456700", TRUNCATE, 100, SIGNIFICANT_DIGITS) == "0.0001234567";
    @test decimalToPrecision(exchange, "0.0001234567", TRUNCATE, 100, SIGNIFICANT_DIGITS) == "0.0001234567";
