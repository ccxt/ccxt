using Test
using Ccxt
function testPrecise()

    w = "-1.123e-6";
    x = "0.00000002";
    y = "69696900000";
    z = "0";
    a = "1e8";
    @test stringMul(x, y) == "1393.938";
    @test stringMul(y, x) == "1393.938";
    @test stringAdd(x, y) == "69696900000.00000002";
    @test stringAdd(y, x) == "69696900000.00000002";
    @test stringSub(x, y) == "-69696899999.99999998";
    @test stringSub(y, x) == "69696899999.99999998";
    @test stringDiv(x, y, 1) == "0";
    @test stringDiv(x, y) == "0";
    @test stringDiv(x, y, 19) == "0.0000000000000000002";
    @test stringDiv(x, y, 20) == "0.00000000000000000028";
    @test stringDiv(x, y, 21) == "0.000000000000000000286";
    @test stringDiv(x, y, 22) == "0.0000000000000000002869";
    @test stringDiv(y, x) == "3484845000000000000";
    @test stringMul(x, w) == "-0.00000000000002246";
    @test stringMul(w, x) == "-0.00000000000002246";
    @test stringAdd(x, w) == "-0.000001103";
    @test stringAdd(w, x) == "-0.000001103";
    @test stringSub(x, w) == "0.000001143";
    @test stringSub(w, x) == "-0.000001143";
    @test stringDiv(x, w) == "-0.017809439002671415";
    @test stringDiv(w, x) == "-56.15";
    @test stringMul(z, w) == "0";
    @test stringMul(z, x) == "0";
    @test stringMul(z, y) == "0";
    @test stringMul(w, z) == "0";
    @test stringMul(x, z) == "0";
    @test stringMul(y, z) == "0";
    @test stringAdd(z, w) == "-0.000001123";
    @test stringAdd(z, x) == "0.00000002";
    @test stringAdd(z, y) == "69696900000";
    @test stringAdd(w, z) == "-0.000001123";
    @test stringAdd(x, z) == "0.00000002";
    @test stringAdd(y, z) == "69696900000";
    @test stringMul(x, a) == "2";
    @test stringMul(a, x) == "2";
    @test stringMul(y, a) == "6969690000000000000";
    @test stringMul(a, y) == "6969690000000000000";
    @test stringDiv(y, a) == "696.969";
    @test stringDiv(y, a, -1) == "690";
    @test stringDiv(y, a, 0) == "696";
    @test stringDiv(y, a, 1) == "696.9";
    @test stringDiv(y, a, 2) == "696.96";
    @test stringDiv(a, y) == "0.001434784043479695";
    @test stringAbs("0") == "0";
    @test stringAbs("-0") == "0";
    @test stringAbs("-500.1") == "500.1";
    @test stringAbs("213") == "213";
    @test stringNeg("0") == "0";
    @test stringNeg("-0") == "0";
    @test stringNeg("-500.1") == "500.1";
    @test stringNeg("213") == "-213";
    @test stringMod("57.123", "10") == "7.123";
    @test stringMod("18", "6") == "0";
    @test stringMod("10.1", "0.5") == "0.1";
    @test stringMod("10000000", "5555") == "1000";
    @test stringMod("5550", "120") == "30";
    @test functions.ccxtruthy(stringEquals("1.0000", "1"));
    @test functions.ccxtruthy(stringEquals("-0.0", "0"));
    @test functions.ccxtruthy(stringEquals("-0.0", "0.0"));
    @test functions.ccxtruthy(stringEquals("5.534000", "5.5340"));
    @test stringMin("1.0000", "2") == "1";
    @test stringMin("2", "1.2345") == "1.2345";
    @test stringMin("3.1415", "-2") == "-2";
    @test stringMin("-3.1415", "-2") == "-3.1415";
    @test stringMin("0.000", "-0.0") == "0";
    @test stringMax("1.0000", "2") == "2";
    @test stringMax("2", "1.2345") == "2";
    @test stringMax("3.1415", "-2") == "3.1415";
    @test stringMax("-3.1415", "-2") == "-2";
    @test stringMax("0.000", "-0.0") == "0";
    @test !functions.ccxtruthy(stringGt("1.0000", "2"));
    @test functions.ccxtruthy(stringGt("2", "1.2345"));
    @test functions.ccxtruthy(stringGt("3.1415", "-2"));
    @test !functions.ccxtruthy(stringGt("-3.1415", "-2"));
    @test !functions.ccxtruthy(stringGt("3.1415", "3.1415"));
    @test functions.ccxtruthy(stringGt("3.14150000000000000000001", "3.1415"));
    @test !functions.ccxtruthy(stringGe("1.0000", "2"));
    @test functions.ccxtruthy(stringGe("2", "1.2345"));
    @test functions.ccxtruthy(stringGe("3.1415", "-2"));
    @test !functions.ccxtruthy(stringGe("-3.1415", "-2"));
    @test functions.ccxtruthy(stringGe("3.1415", "3.1415"));
    @test functions.ccxtruthy(stringGe("3.14150000000000000000001", "3.1415"));
    @test functions.ccxtruthy(stringLt("1.0000", "2"));
    @test !functions.ccxtruthy(stringLt("2", "1.2345"));
    @test !functions.ccxtruthy(stringLt("3.1415", "-2"));
    @test functions.ccxtruthy(stringLt("-3.1415", "-2"));
    @test !functions.ccxtruthy(stringLt("3.1415", "3.1415"));
    @test functions.ccxtruthy(stringLt("3.1415", "3.14150000000000000000001"));
    @test functions.ccxtruthy(stringLe("1.0000", "2"));
    @test !functions.ccxtruthy(stringLe("2", "1.2345"));
    @test !functions.ccxtruthy(stringLe("3.1415", "-2"));
    @test functions.ccxtruthy(stringLe("-3.1415", "-2"));
    @test functions.ccxtruthy(stringLe("3.1415", "3.1415"));
    @test functions.ccxtruthy(stringLe("3.1415", "3.14150000000000000000001"));
    @test stringOr("5", "3") == "7";
    @test stringOr("10", "5") == "15";
    @test stringOr("0", "0") == "0";
    @test stringOr("7", "0") == "7";
    @test stringMul(nothing, "1") == nothing;
    @test stringMul("1", nothing) == nothing;
    @test stringMul(nothing, nothing) == nothing;
    @test stringDiv(nothing, "1") == nothing;
    @test stringDiv("1", nothing) == nothing;
    @test stringDiv(nothing, nothing) == nothing;
    @test stringAdd(nothing, "1") == nothing;
    @test stringAdd("1", nothing) == nothing;
    @test stringAdd(nothing, nothing) == nothing;
    @test stringSub(nothing, "1") == nothing;
    @test stringSub("1", nothing) == nothing;
    @test stringSub(nothing, nothing) == nothing;
    @test stringAbs(nothing) == nothing;
    @test stringNeg(nothing) == nothing;
    @test stringMod(nothing, "1") == nothing;
    @test stringMod("1", nothing) == nothing;
    @test stringMod(nothing, nothing) == nothing;
    @test stringOr(nothing, "1") == nothing;
    @test stringOr("1", nothing) == nothing;
    @test stringOr(nothing, nothing) == nothing;
    @test stringMin(nothing, "1") == nothing;
    @test stringMin("1", nothing) == nothing;
    @test stringMin(nothing, nothing) == nothing;
    @test stringMax(nothing, "1") == nothing;
    @test stringMax("1", nothing) == nothing;
    @test stringMax(nothing, nothing) == nothing;
    @test stringEquals(nothing, "1") == false;
    @test stringEquals("1", nothing) == false;
    @test stringEquals(nothing, nothing) == false;
    @test stringEq(nothing, "1") == false;
    @test stringEq("1", nothing) == false;
    @test stringEq(nothing, nothing) == false;
    @test stringGt(nothing, "1") == false;
    @test stringGt("1", nothing) == false;
    @test stringGt(nothing, nothing) == false;
    @test stringGe(nothing, "1") == false;
    @test stringGe("1", nothing) == false;
    @test stringGe(nothing, nothing) == false;
    @test stringLt(nothing, "1") == false;
    @test stringLt("1", nothing) == false;
    @test stringLt(nothing, nothing) == false;
    @test stringLe(nothing, "1") == false;
    @test stringLe("1", nothing) == false;
    @test stringLe(nothing, nothing) == false;
end
