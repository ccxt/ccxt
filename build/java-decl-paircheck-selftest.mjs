#!/usr/bin/env node
// DEV TOOL — campaign instrumentation for the Java nested-types typing campaign (JN-24).
// NOT wired into any published build; safe to exclude from release PRs.
//
// SELF-TEST for build/java-decl-paircheck.mjs. A checker that reports "0 problems"
// without ever having been shown a problem is worthless (a previous campaign shipped
// exactly that). This self-test builds a scratch git repo with a generated-style Java
// file, applies known GOOD mutations (declaration/signature/cast-only) and known BAD
// mutations (value/identifier/literal/statement changes), runs the REAL validator
// binary against each resulting git diff, and asserts:
//   * GOOD cases          -> exit 0, zero violations
//   * BAD cases           -> exit 1, the expected violation category AND the offending
//                            line is present in the report
//   * comment-only change -> exit 0 with a warning (exit 1 with --strict)
//   * mixed good+bad      -> exit 1 with exactly the one bad change flagged
//
// Usage: node build/java-decl-paircheck-selftest.mjs [--keep] [--validator <path>]
// Exit: 0 = SELFTEST PASSED, 1 = SELFTEST FAILED.

import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync, spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const DEFAULT_VALIDATOR = path.join(SCRIPT_DIR, 'java-decl-paircheck.mjs');

const argv = process.argv.slice(2);
let keep = false;
let validator = DEFAULT_VALIDATOR;
for (let i = 0; i < argv.length; i++) {
  if (argv[i] === '--keep') keep = true;
  else if (argv[i] === '--validator') validator = argv[++i];
}

const BASELINE = `// PLEASE DO NOT EDIT THIS FILE, IT IS GENERATED AND WILL BE OVERWRITTEN:
// https://github.com/ccxt/ccxt/blob/master/CONTRIBUTING.md#how-to-contribute-code

package sample;
import io.github.ccxt.Helpers;

public class Sample
{
    public Object fetchThings(Object... optionalArgs) {
        Object parameters = Helpers.getArg(optionalArgs, 0, new java.util.HashMap<String, Object>() {{}});
        Object response = (this.privateGetThings(parameters)).join();
        // fetch the raw rows from the response
        Object data = this.safeValue(response, "data", new java.util.ArrayList<Object>(java.util.Arrays.asList()));
        Object qty = 0.01;
        Object order = this.safeDict(response, "order");
        Object market = this.safeMarket("BTC/USDT", null);
        String marketId = this.safeString(market, "id");
        Object total = this.safeInteger2(order, "a", "b");
        Object status = this.parseStatus(this.safeString(order, "status"));
        java.util.List<Object> results = new java.util.ArrayList<Object>(java.util.Arrays.asList());
        Object ticker = this.parseTicker(data);
        results.add(ticker);
        Object cond = true;
        String hash = cond ? "a" : "b";
        Object timeout = 10;
        put( "timeout", Helpers.isGreaterThan(timeout, 0) ? this.parseToInt(1) : 0 );
        market = this.safeMarket(marketId, market);
        return data;
    }

    public Object parseStatus(Object status)
    {
        Object normalized = this.safeString(status, 0);
        return normalized;
    }

    public Object parseTicker(Object data)
    {
        Object ticker = new java.util.HashMap<String, Object>() {{}};
        return ticker;
    }
}
`;

// [name, oldFragment, newFragment, expectation]
// expectation: {exit: 0|1, category?: string, expectLine?: string, strict?: bool, count?: number}
const CASES = [
  // ---- GOOD: declaration/signature/cast-only changes ----
  ['G1 decl+cast', 'Object total = this.safeInteger2(order, "a", "b");',
    'Long total = (Long) this.safeInteger2(order, "a", "b");', { exit: 0 }],
  ['G2 signature+local', 'public Object parseStatus(Object status)',
    'public String parseStatus(Object status)', { exit: 0 }],
  ['G2b local from retyped', 'Object status = this.parseStatus(this.safeString(order, "status"));',
    'String status = this.parseStatus(this.safeString(order, "status"));', { exit: 0 }],
  ['G3 receiver cast', '        results.add(ticker);',
    '        ((java.util.List<Object>) results).add(ticker);', { exit: 0 }],
  ['G4 boolean local', 'Object cond = true;', 'Boolean cond = true;', { exit: 0 }],
  ['G5 cast wraps ternary', 'String hash = cond ? "a" : "b";',
    'String hash = (String) (cond ? "a" : "b");', { exit: 0 }],
  ['G6 nominal type', 'Object ticker = this.parseTicker(data);',
    'io.github.ccxt.types.Ticker ticker = (io.github.ccxt.types.Ticker) this.parseTicker(data);', { exit: 0 }],
  ['G7 ternary-branch cast', 'put( "timeout", Helpers.isGreaterThan(timeout, 0) ? this.parseToInt(1) : 0 );',
    'put( "timeout", Helpers.isGreaterThan(timeout, 0) ? ((Object) this.parseToInt(1)) : 0 );', { exit: 0 }],
  ['G8 import add', 'import io.github.ccxt.Helpers;',
    'import io.github.ccxt.Helpers;\nimport java.util.List;', { exit: 0 }],
  ['G9 whitespace only', 'Object qty = 0.01;', 'Object qty  =  0.01;', { exit: 0 }],

  // ---- BAD: runtime-relevant changes that MUST be flagged ----
  ['B1 number change', 'Object qty = 0.01;', 'Object qty = 0.02;',
    { exit: 1, category: 'VALUE_CHANGE', expectLine: '0.02' }],
  ['B2 string literal change', 'this.safeString(market, "id")', 'this.safeString(market, "ident")',
    { exit: 1, category: 'VALUE_CHANGE', expectLine: 'ident' }],
  ['B3 identifier rename', 'Object order = this.safeDict(response, "order");',
    'Object ord = this.safeDict(response, "order");', { exit: 1, category: 'VALUE_CHANGE', expectLine: 'ord ' }],
  ['B4 statement removed', '        market = this.safeMarket(marketId, market);\n', '',
    { exit: 1, category: 'UNPAIRED_REMOVE', expectLine: 'safeMarket' }],
  ['B5 statement added', '        Object timeout = 10;',
    '        Object timeout = 10;\n        Helpers.add(results, ticker);', { exit: 1, category: 'UNPAIRED_ADD', expectLine: 'Helpers.add' }],
  ['B6 ternary arms swapped', 'String hash = cond ? "a" : "b";', 'String hash = cond ? "b" : "a";',
    { exit: 1, category: 'VALUE_CHANGE' }],
  ['B7 cast-ternary bug', 'String hash = cond ? "a" : "b";', 'String hash = (String) cond ? "a" : "b";',
    { exit: 1, category: 'CAST_TERNARY_SUSPECT' }],
  ['B8 argument change', 'this.parseToInt(1)', 'this.parseToInt(2)',
    { exit: 1, category: 'VALUE_CHANGE', expectLine: 'parseToInt(2)' }],
  ['B9 helper swap', 'Object data = this.safeValue(response, "data"', 'Object data = this.safeList(response, "data"',
    { exit: 1, category: 'VALUE_CHANGE', expectLine: 'safeList' }],

  // ---- comment-only: warning by default, violation under --strict ----
  ['C1 comment change (warn)', '// fetch the raw rows from the response', '// fetch the raw rows',
    { exit: 0, warnCount: 1 }],
  ['C1s comment change (strict)', '// fetch the raw rows from the response', '// fetch the raw rows',
    { exit: 1, category: 'COMMENT_CHANGE', strict: true }],

  // ---- mixed: several good changes PLUS one bad -> exactly the bad one flagged ----
  ['M1 mixed good+bad', 'Object qty = 0.01;', 'Double qty = 0.99;',
    { exit: 1, category: 'VALUE_CHANGE', expectLine: '0.99', extraGood: true }],
];

function run(cmd, args, opts = {}) {
  return spawnSync(cmd, args, { encoding: 'utf8', ...opts });
}

function sh(cmd, args, cwd) {
  return execFileSync(cmd, args, { cwd, encoding: 'utf8' });
}

const scratch = fs.mkdtempSync(path.join(os.tmpdir(), 'jn-paircheck-selftest-'));
const file = path.join(scratch, 'Sample.java');
let allPass = true;
const rows = [];

function reset() {
  fs.writeFileSync(file, BASELINE);
}

function applyMutation(oldFrag, newFrag) {
  const text = fs.readFileSync(file, 'utf8');
  if (!text.includes(oldFrag)) throw new Error(`baseline does not contain: ${JSON.stringify(oldFrag)}`);
  fs.writeFileSync(file, text.replace(oldFrag, newFrag));
}

function applyGoodExtra() {
  // used by the mixed case: several legit declaration changes + one bad change
  let t = fs.readFileSync(file, 'utf8');
  t = t.replace('Object total = this.safeInteger2(order, "a", "b");', 'Long total = (Long) this.safeInteger2(order, "a", "b");');
  t = t.replace('Object status = this.parseStatus(this.safeString(order, "status"));', 'String status = this.parseStatus(this.safeString(order, "status"));');
  t = t.replace('        results.add(ticker);', '        ((java.util.List<Object>) results).add(ticker);');
  fs.writeFileSync(file, t);
}

try {
  sh('git', ['init', '-q'], scratch);
  sh('git', ['config', 'user.email', 'selftest@example.com'], scratch);
  sh('git', ['config', 'user.name', 'selftest'], scratch);
  reset();
  sh('git', ['add', 'Sample.java'], scratch);
  sh('git', ['commit', '-qm', 'baseline'], scratch);

  // sanity: clean tree -> 0 violations
  {
    const json = path.join(scratch, 'out.json');
    const r = run('node', [validator, '--worktree', scratch, '--base', 'HEAD', '--paths', 'Sample.java', '--json', json, '--quiet']);
    const rep = JSON.parse(fs.readFileSync(json, 'utf8'));
    const pass = r.status === 0 && rep.totals.violations === 0;
    allPass = allPass && pass;
    rows.push(['N0 clean tree', 'exit 0, 0 viol', `exit ${r.status}, ${rep.totals.violations} viol`, pass]);
  }

  for (const [name, oldFrag, newFrag, exp] of CASES) {
    reset();
    if (name === 'G7 ternary-branch cast' || name === 'G5 cast wraps ternary') {
      // these target lines that exist in the baseline as-is
    }
    if (exp.extraGood) applyGoodExtra();
    applyMutation(oldFrag, newFrag);
    const json = path.join(scratch, 'out.json');
    const args = [validator, '--worktree', scratch, '--base', 'HEAD', '--paths', 'Sample.java', '--json', json, '--quiet'];
    if (exp.strict) args.push('--strict');
    const r = run('node', args);
    let rep = null;
    try { rep = JSON.parse(fs.readFileSync(json, 'utf8')); } catch (e) { /* no json */ }
    let pass = false;
    let got = `exit ${r.status}`;
    if (rep) {
      got += `, ${rep.totals.violations} viol, ${rep.totals.warnings} warn`;
      if (exp.exit === 0) {
        pass = r.status === 0 && rep.totals.violations === 0;
        if (exp.warnCount !== undefined) pass = pass && rep.totals.warnings === exp.warnCount;
      } else {
        pass = r.status === 1 && rep.totals.violations === 1;
        if (exp.category) {
          const vs = rep.files.flatMap((f) => f.violations);
          pass = pass && vs.length === 1 && vs[0].category === exp.category;
        }
        if (exp.expectLine) {
          const text = JSON.stringify(rep);
          pass = pass && text.includes(exp.expectLine);
        }
      }
    }
    allPass = allPass && pass;
    rows.push([name, `exit ${exp.exit}${exp.category ? ', ' + exp.category : ''}${exp.warnCount !== undefined ? ', warn=' + exp.warnCount : ''}`, got, pass]);
  }
} finally {
  if (!keep) fs.rmSync(scratch, { recursive: true, force: true });
  else console.log(`scratch kept at ${scratch}`);
}

const w = Math.max(...rows.map((r) => r[0].length));
console.log('java-decl-paircheck selftest — injected-change detection proof');
console.log('');
for (const [name, exp, got, pass] of rows) {
  console.log(`${name.padEnd(w)}  expect: ${exp.padEnd(38)} got: ${got.padEnd(28)} ${pass ? 'PASS' : 'FAIL'}`);
}
const failed = rows.filter((r) => !r[3]).length;
console.log('');
console.log(allPass ? `SELFTEST PASSED (${rows.length}/${rows.length} cases)` : `SELFTEST FAILED (${rows.length - failed}/${rows.length} cases)`);
process.exit(allPass ? 0 : 1);
