// hx10 wave-2 G04 (Go): typed operand comparisons for the IsEqual / ordered-comparison / truthiness helper family.
//
// The printer emits `IsEqual(a, b)` / `IsGreaterThan(a, b)` / `EvalTruthy(x)` whenever it cannot type an operand, and
// ccxt's retype tables then name the local after printing (`var x any` -> `var x *string`), so the emitted text holds
// a declaration type the printer never saw. This pass reads that declaration and emits the plain Go operator:
// `==` `<` `>` on int/int64/float64/string/bool, `*T == nil` and `*L > *R` behind the helper's own nil predicate.
// An operand this block does not prove keeps the helper call byte for byte.
//
// The nil/NaN arms mirror `derefScalar` plus the helper bodies in go/v4/exchange_helpers.go:
//   IsEqual: deref both; nil/nil true, one nil false, then width-promoted numeric, string and bool.
//   IsGreaterThan: `a != nil && b == nil` -> true, `a == nil || b == nil` -> false, else a numeric `>` only.
//   IsLessThan = !GT && !EQ, GE = GT || EQ, LE = LT || EQ, so float64 keeps `<`/`<=`
//   (the helper calls NaN "less than").

const G04_BANNER = 'PLEASE DO NOT EDIT THIS FILE';
// Struct fields whose every assignment in the regenerated tree is a non-nil container or a plain string value, so
// the field box can never hold a nil pointer: `IsEqual(this.F, nil)` is the interface nil test itself. Evidence is
// the whole write set of each name (grep `\.<Field> = ` over go/v4): all `map[string]any{}` literals, or a
// `.(string)` / `.(map[string]any)` assertion, which panics rather than storing anything else.
const G04_NIL_FIELDS = new Set ([ 'Outcomes', 'Outcomes_by_id', 'Events_by_slug', 'Features', 'ProxyUrl' ]);
const G04_SOURCE = '(?<![\\w.])(?:ccxt\\.)?(IsEqual|IsGreaterThanOrEqual|IsLessThanOrEqual|IsGreaterThan|IsLessThan|EvalTruthy|IsTrue)\\(';

interface G04Operand {
    'isNil'?: boolean;
    'base'?: string;
    'ptr'?: boolean;
    'isConst'?: boolean;
    'text': string;
}

interface G04Type {
    'base': string;
    'ptr': boolean;
}

// same-length mask: comment bodies and string-literal contents become spaces, the quotes stay
function g04Mask (text: string): string {
    const out = text.split ('');
    const n = text.length;
    let i = 0;
    let block = false;
    while (i < n) {
        const c = text[i];
        if (block) {
            if ((c === '*') && (text[i + 1] === '/')) {
                out[i] = ' ';
                out[i + 1] = ' ';
                i += 2;
                block = false;
                continue;
            }
            if (c !== '\n') {
                out[i] = ' ';
            }
            i++;
            continue;
        }
        if ((c === '/') && (text[i + 1] === '/')) {
            const j = text.indexOf ('\n', i);
            const stop = (j < 0) ? n : j;
            for (let k = i; k < stop; k++) {
                out[k] = ' ';
            }
            i = stop;
            continue;
        }
        if ((c === '/') && (text[i + 1] === '*')) {
            block = true;
            out[i] = ' ';
            out[i + 1] = ' ';
            i += 2;
            continue;
        }
        if ((c === '"') || (c === '`')) {
            const quote = c;
            let j = i + 1;
            while (j < n) {
                if ((quote === '"') && (text[j] === '\\')) {
                    j += 2;
                    continue;
                }
                if (text[j] === quote) {
                    break;
                }
                if ((quote === '"') && (text[j] === '\n')) {
                    break;
                }
                j++;
            }
            for (let k = i + 1; k < j; k++) {
                if (text[k] !== '\n') {
                    out[k] = ' ';
                }
            }
            i = j + 1;
            continue;
        }
        i++;
    }
    return out.join ('');
}

function g04Args (masked: string, open: number): { 'args': string[], 'end': number } | undefined {
    const args: string[] = [];
    let depth = 0;
    let from = open + 1;
    for (let i = open + 1; i < masked.length; i++) {
        const c = masked[i];
        if ((c === '(') || (c === '[') || (c === '{')) {
            depth++;
        } else if ((c === ')') || (c === ']') || (c === '}')) {
            if (depth === 0) {
                args.push (masked.slice (from, i).trim ());
                return { 'args': args, 'end': i };
            }
            depth--;
        } else if ((c === ',') && (depth === 0)) {
            args.push (masked.slice (from, i).trim ());
            from = i + 1;
        }
    }
    return undefined;
}

function g04Blocks (maskedLines: string[]): { 'start': number, 'end': number }[] {
    const blocks: { 'start': number, 'end': number }[] = [];
    for (let i = 0; i < maskedLines.length; i++) {
        if (!maskedLines[i].startsWith ('func ')) {
            continue;
        }
        let end = i;
        while ((end < maskedLines.length) && (maskedLines[end] !== '}') && !((end === i) && maskedLines[i].endsWith ('}'))) {
            end++;
        }
        if (end >= maskedLines.length) {
            end = maskedLines.length - 1;
        }
        blocks.push ({ 'start': i, 'end': end });
        i = end;
    }
    return blocks;
}

// every `var x T` / parameter `x T` of the block; `null` marks a name whose type is not provable
function g04DeclTypes (maskedLines: string[], start: number, end: number): Map<string, G04Type | null> {
    const seen = new Map<string, G04Type | null> ();
    const record = (name: string, base: string, ptr: boolean) => {
        const known = seen.get (name);
        if (known === null) {
            return;
        }
        if (known === undefined) {
            seen.set (name, { 'base': base, 'ptr': ptr });
            return;
        }
        if ((known.base !== base) || (known.ptr !== ptr)) {
            seen.set (name, null);
        }
    };
    if (maskedLines[start] === undefined) {
        return seen;
    }
    let headerEnd = start;
    while ((headerEnd <= end) && (maskedLines[headerEnd].indexOf ('{') < 0)) {
        headerEnd++;
    }
    const signature = maskedLines.slice (start, headerEnd + 1).join (' ').split ('{')[0];
    const paramRe = /(?:^|[(,])\s*(\w+)\s+(\*?)(int64|float64|string|bool|int)\b/g;
    let match: RegExpExecArray | null;
    while ((match = paramRe.exec (signature)) !== null) {
        if (match[1] !== 'this') {
            record (match[1], match[3], match[2] === '*');
        }
    }
    const anyParamRe = /(?:^|[(,])\s*(\w+)\s+(?:any|\[\]any|map\[string\]any)\b/g;
    while ((match = anyParamRe.exec (signature)) !== null) {
        if (match[1] !== 'this') {
            seen.set (match[1], null);
        }
    }
    const closureParams = /\bfunc\s*\(([^)]*)\)/g;
    for (let i = start + 1; i <= end; i++) {
        const line = maskedLines[i];
        let shadow: RegExpExecArray | null;
        while ((shadow = closureParams.exec (line)) !== null) {
            for (const part of shadow[1].split (',')) {
                const name = /^\s*(\w+)\s+\S/.exec (part);
                if (name !== null) {
                    seen.set (name[1], null);
                }
            }
        }
        const decl = /^\s*var (\w+) (\*?)(int64|float64|string|bool|int)\b/.exec (line);
        if (decl !== null) {
            record (decl[1], decl[3], decl[2] === '*');
            continue;
        }
        const loop = /^\s*for (\w+)(?:\s*,\s*(\w+))?\s*:=\s*-?\d+\s*;/.exec (line);
        if (loop !== null) {
            record (loop[1], 'int', false);
            continue;
        }
        const other = /^\s*var (\w+) /.exec (line);
        if (other !== null) {
            seen.set (other[1], null);
            continue;
        }
        const short = /^\s*(\w+)(?:\s*,\s*\w+)*\s*:=/.exec (line);
        if (short !== null) {
            seen.set (short[1], null);
        }
    }
    return seen;
}

// balanced outer parens are redundant for the operand's type
function g04Unwrap (text: string): string {
    let s = text.trim ();
    while ((s.length > 2) && s.startsWith ('(') && s.endsWith (')')) {
        let depth = 0;
        let closes = true;
        for (let i = 0; i < s.length; i++) {
            if (s[i] === '(') {
                depth++;
            } else if (s[i] === ')') {
                depth--;
                if ((depth === 0) && (i !== s.length - 1)) {
                    closes = false;
                    break;
                }
            }
        }
        if (!closes) {
            break;
        }
        s = s.slice (1, -1).trim ();
    }
    return s;
}

// method / function names this file declares returning a plain Go `bool`
function g04BoolCalls (masked: string): Set<string> {
    const yes = new Set<string> ();
    const no = new Set<string> ();
    const rx = /func (?:\(this \*\w+\) )?(\w+)\(([^{]*)\) ([^{]+) \{/g;
    let match: RegExpExecArray | null;
    while ((match = rx.exec (masked)) !== null) {
        if (match[3].trim () === 'bool') {
            yes.add (match[1]);
        } else {
            no.add (match[1]);
        }
    }
    for (const name of no) {
        yes.delete (name);
    }
    return yes;
}

function g04Classify (maskedArg: string, bools: Set<string> = new Set<string> ()): G04Operand | undefined {
    const text = g04Unwrap (maskedArg);
    if (text === 'nil') {
        return { 'isNil': true, 'text': 'nil' };
    }
    if (/^"[\s]*"$/.test (text)) {
        return { 'base': 'string', 'ptr': false, 'text': text };
    }
    if (/^-?\d+$/.test (text)) {
        return { 'base': (text.replace ('-', '').length > 18) ? 'wide' : 'int64', 'ptr': false, 'isConst': true, 'text': text };
    }
    if (/^-?\d+\.\d+(?:[eE][-+]?\d+)?$/.test (text) || /^-?\d+[eE][-+]?\d+$/.test (text)) {
        return { 'base': 'float64', 'ptr': false, 'isConst': true, 'text': text };
    }
    const cast = /^(int64|float64)\((-?\d+)\)$/.exec (text);
    if (cast !== null) {
        return { 'base': cast[1], 'ptr': false, 'isConst': true, 'text': text };
    }
    if (/^\w+$/.test (text)) {
        return { 'text': text };
    }
    const field = /^this\.(\w+)$/.exec (text);
    if ((field !== null) && G04_NIL_FIELDS.has (field[1])) {
        return { 'base': 'anycontainer', 'ptr': false, 'text': text };
    }
    if (/^len\(.*\)$/.test (text)) {
        return { 'base': 'int', 'ptr': false, 'text': text };
    }
    const call = /^(?:this\.)?(\w+)\(/.exec (text);
    if ((call !== null) && bools.has (call[1]) && /^this\.\w+\([\s\S]*\)$|^\w+\([\s\S]*\)$/.test (text)) {
        return { 'base': 'bool', 'ptr': false, 'text': text };
    }
    return undefined;
}

function g04NotNum (t: string): boolean {
    return (t !== 'int') && (t !== 'int64') && (t !== 'float64');
}

function g04Join (l: string, r: string): string | undefined {
    if (l === r) {
        return l;
    }
    if (g04NotNum (l) || g04NotNum (r)) {
        return undefined;
    }
    if ((l === 'float64') || (r === 'float64')) {
        return 'float64';
    }
    return 'int64';
}

function g04Cast (expr: string, from: string, to: string): string {
    return (from === to) ? expr : to + '(' + expr + ')';
}

function g04Val (op: G04Operand, join: string): string {
    return (op.isConst === true) ? op.text : g04Cast (op.text, op.base as string, join);
}

// `==` / `!=` on two proven operands; undefined keeps the helper
function g04Eq (left: G04Operand, right: G04Operand, negated: boolean): string | undefined {
    if ((left.isNil === true) || (right.isNil === true)) {
        const other = (left.isNil === true) ? right : left;
        if ((other.ptr !== true) && (other.base !== 'anycontainer')) {
            return undefined;
        }
        return '(' + other.text + (negated ? ' != nil)' : ' == nil)');
    }
    if ((left.base === undefined) || (right.base === undefined)) {
        return undefined;
    }
    const l = left.text;
    const r = right.text;
    if ((left.ptr === true) && (right.ptr === true)) {
        if (left.base !== right.base) {
            return undefined;
        }
        return negated
            ? '(' + l + ' != ' + r + ' && (' + l + ' == nil || ' + r + ' == nil || *' + l + ' != *' + r + '))'
            : '(' + l + ' == ' + r + ' || (' + l + ' != nil && ' + r + ' != nil && *' + l + ' == *' + r + '))';
    }
    if ((left.ptr === true) || (right.ptr === true)) {
        const ptr = (left.ptr === true) ? left : right;
        const val = (left.ptr === true) ? right : left;
        const p = ptr.text;
        const inner = '*' + p;
        if (val.isConst === true) {
            const lit = val.text;
            const lhs = (left.ptr === true) ? inner : lit;
            const rhs = (left.ptr === true) ? lit : inner;
            return negated ? '(' + p + ' == nil || ' + lhs + ' != ' + rhs + ')' : '(' + p + ' != nil && ' + lhs + ' == ' + rhs + ')';
        }
        const join = g04Join (ptr.base as string, val.base as string);
        if ((join === undefined) || (join !== (ptr.base as string))) {
            return undefined;
        }
        const value = g04Val (val, join);
        const lhs = (left.ptr === true) ? inner : value;
        const rhs = (left.ptr === true) ? value : inner;
        return negated ? '(' + p + ' == nil || ' + lhs + ' != ' + rhs + ')' : '(' + p + ' != nil && ' + lhs + ' == ' + rhs + ')';
    }
    const join = g04Join (left.base, right.base);
    if (join === undefined) {
        return undefined;
    }
    return '(' + g04Val (left, join) + (negated ? ' != ' : ' == ') + g04Val (right, join) + ')';
}

// `>` / `>=` / `<` / `<=` on two proven numeric operands; undefined keeps the helper
function g04Ord (helper: string, left: G04Operand, right: G04Operand): string | undefined {
    if ((left.isNil === true) || (right.isNil === true)) {
        return undefined;
    }
    if ((left.base === undefined) || (right.base === undefined)) {
        return undefined;
    }
    if (g04NotNum (left.base) || g04NotNum (right.base)) {
        return undefined;
    }
    const ops: { [key: string]: string } = { 'IsGreaterThan': '>', 'IsGreaterThanOrEqual': '>=', 'IsLessThan': '<', 'IsLessThanOrEqual': '<=' };
    const op = ops[helper];
    const join = g04Join (left.base, right.base);
    if ((op === undefined) || (join === undefined)) {
        return undefined;
    }
    if ((join === 'float64') && ((op === '<') || (op === '<='))) {
        return undefined;
    }
    const l = left.text;
    const r = right.text;
    const lv = '*' + l;
    const rv = '*' + r;
    if ((left.ptr !== true) && (right.ptr !== true)) {
        return '(' + g04Val (left, join) + ' ' + op + ' ' + g04Val (right, join) + ')';
    }
    if ((left.ptr === true) && (right.ptr === true)) {
        if (left.base !== right.base) {
            return undefined;
        }
        if (op === '>') {
            return '(' + l + ' != nil && (' + r + ' == nil || ' + lv + ' > ' + rv + '))';
        }
        if (op === '>=') {
            return '(' + r + ' == nil || (' + l + ' != nil && ' + lv + ' >= ' + rv + '))';
        }
        if (op === '<') {
            return '(' + r + ' != nil && (' + l + ' == nil || ' + lv + ' < ' + rv + '))';
        }
        return '(' + l + ' == nil || (' + r + ' != nil && ' + lv + ' <= ' + rv + '))';
    }
    const ptrIsLeft = (left.ptr === true);
    const p = ptrIsLeft ? l : r;
    const pv = ptrIsLeft ? lv : rv;
    const v = ptrIsLeft ? g04Val (right, join) : g04Val (left, join);
    if (ptrIsLeft) {
        if (op === '>') {
            return '(' + p + ' != nil && ' + pv + ' > ' + v + ')';
        }
        if (op === '>=') {
            return '(' + p + ' != nil && ' + pv + ' >= ' + v + ')';
        }
        if (op === '<') {
            return '(' + p + ' == nil || ' + pv + ' < ' + v + ')';
        }
        return '(' + p + ' == nil || ' + pv + ' <= ' + v + ')';
    }
    if (op === '>') {
        return '(' + p + ' == nil || ' + v + ' > ' + pv + ')';
    }
    if (op === '>=') {
        return '(' + p + ' == nil || ' + v + ' >= ' + pv + ')';
    }
    if (op === '<') {
        return '(' + p + ' != nil && ' + v + ' < ' + pv + ')';
    }
    return '(' + p + ' != nil && ' + v + ' <= ' + pv + ')';
}

// EvalTruthy / IsTrue on one proven operand: derefScalar, then the helper's zero test
function g04Truthy (operand: G04Operand): string | undefined {
    const base = operand.base;
    if (base === undefined) {
        return undefined;
    }
    const zero = (expr: string): string => {
        if (base === 'bool') {
            return expr;
        }
        return (base === 'string') ? (expr + ' != ""') : (expr + ' != 0');
    };
    if (operand.ptr === true) {
        return '(' + operand.text + ' != nil && ' + zero ('*' + operand.text) + ')';
    }
    return '(' + zero (operand.text) + ')';
}

function g04Block (lines: string[], maskedLines: string[], start: number, end: number, bools: Set<string>): boolean {
    const types = g04DeclTypes (maskedLines, start, end);
    let blockChanged = false;
    for (let i = end; i >= start; i--) {
        const masked = maskedLines[i];
        if (!new RegExp (G04_SOURCE).test (masked)) {
            continue;
        }
        let out = lines[i];
        let maskedOut = masked;
        let lineChanged = false;
        const rx = new RegExp (G04_SOURCE, 'g');
        const hits = [ ...masked.matchAll (rx) ].reverse ();
        for (const hit of hits) {
            const at = hit.index as number;
            const open = at + hit[0].length - 1;
            const parsed = g04Args (masked, open);
            if (parsed === undefined) {
                continue;
            }
            const helper = hit[1];
            const args = parsed.args;
            let native: string | undefined;
            if ((helper === 'EvalTruthy') || (helper === 'IsTrue')) {
                if (args.length !== 1) {
                    continue;
                }
                const operand = g04Classify (args[0], bools);
                if ((operand === undefined) || (operand.isConst === true) || (operand.isNil === true)) {
                    continue;
                }
                if (operand.base === undefined) {
                    const declared = types.get (operand.text);
                    if ((declared === undefined) || (declared === null)) {
                        continue;
                    }
                    operand.ptr = declared.ptr;
                    operand.base = declared.base;
                }
                native = g04Truthy (operand);
            } else {
                if (args.length !== 2) {
                    continue;
                }
                const left = g04Classify (args[0], bools);
                const right = g04Classify (args[1], bools);
                if ((left === undefined) || (right === undefined)) {
                    continue;
                }
                let proven = true;
                for (const operand of [ left, right ]) {
                    if ((operand.isNil === true) || (operand.isConst === true) || (operand.base !== undefined)) {
                        continue;
                    }
                    const declared = types.get (operand.text);
                    if ((declared === undefined) || (declared === null)) {
                        proven = false;
                        break;
                    }
                    operand.ptr = declared.ptr;
                    operand.base = declared.base;
                }
                if (!proven) {
                    continue;
                }
                const negated = masked.slice (0, at).trimEnd ().endsWith ('!');
                if (helper === 'IsEqual') {
                    native = g04Eq (left, right, negated);
                } else {
                    native = g04Ord (helper, left, right);
                    if ((native !== undefined) && negated) {
                        native = '!(' + native.slice (1, -1) + ')';
                    }
                }
            }
            if (native === undefined) {
                continue;
            }
            const negated = masked.slice (0, at).trimEnd ().endsWith ('!') && (out[at - 1] === '!');
            const from = negated ? (at - 1) : at;
            let emit = native;
            // gofmt prints a control-clause condition without its outer parens and collapses `((e))` to `(e)`, so
            // the wrapper is dropped where an ambient pair (the condition, an argument) already wraps the call
            const before = masked.slice (0, from).trimEnd ();
            const after = masked.slice (parsed.end + 1);
            if (emit.startsWith ('(') && emit.endsWith (')')) {
                const control = /(?:^|[^\w])(?:if|for|switch)$/.test (before) && /^\s*(?:\{|;)/.test (after);
                const wrapped = before.endsWith ('(') && after.startsWith (')');
                if (control || wrapped) {
                    emit = emit.slice (1, -1);
                }
            }
            out = out.slice (0, from) + emit + out.slice (parsed.end + 1);
            maskedOut = maskedOut.slice (0, from) + ' '.repeat (emit.length) + maskedOut.slice (parsed.end + 1);
            lineChanged = true;
        }
        if (lineChanged) {
            lines[i] = out;
            maskedLines[i] = maskedOut;
            blockChanged = true;
        }
    }
    return blockChanged;
}

export function hx10w2G04 (content: string): string {
    if ((content.indexOf (G04_BANNER) < 0) || !new RegExp (G04_SOURCE).test (content)) {
        return content;
    }
    const lines = content.split ('\n');
    const maskedText = g04Mask (content);
    const maskedLines = maskedText.split ('\n');
    const blocks = g04Blocks (maskedLines);
    const bools = g04BoolCalls (maskedText);
    let changed = false;
    for (let b = blocks.length - 1; b >= 0; b--) {
        changed = g04Block (lines, maskedLines, blocks[b].start, blocks[b].end, bools) || changed;
    }
    return changed ? lines.join ('\n') : content;
}

export function g04Check (): string[] {
    const problems: string[] = [];
    const ok = (cond: boolean, what: string) => { if (!cond) { problems.push ('hx10 G04: ' + what); } };
    const head = 'package ccxt\n\n// PLEASE DO NOT EDIT THIS FILE, IT IS GENERATED AND WILL BE OVERWRITTEN:\n\n';
    const f = (body: string): string => hx10w2G04 (head + 'func (this *X) F(p any) any {\n' + body + '\treturn nil\n}\n');
    // the retype tables name these after printing: the printer never saw the type
    const pair = f ('\tvar a *string = this.SafeString(p, "a")\n\tvar b *string = this.SafeString(p, "b")\n\tif IsEqual(a, b) {\n\t}\n');
    ok (pair.includes ('if a == b || (a != nil && b != nil && *a == *b) {'), 'two *string locals compare natively: ' + pair);
    const negated = f ('\tvar a *string = this.SafeString(p, "a")\n\tvar b *string = this.SafeString(p, "b")\n\tif !IsEqual(a, b) {\n\t}\n');
    ok (negated.includes ('if a != b && (a == nil || b == nil || *a != *b) {'), 'the negated form flips the predicate: ' + negated);
    const ptrVal = f ('\tvar m *int64 = this.SafeInteger(p, "m")\n\tif IsEqual(m, int64(-1)) {\n\t}\n');
    ok (ptrVal.includes ('if m != nil && *m == int64(-1) {'), 'a pointer against a literal is nil-guarded: ' + ptrVal);
    const ordered = f ('\tvar v *int64 = this.SafeInteger(p, "v")\n\tvar s *int64 = this.SafeInteger(p, "s")\n\tvar t int64 = this.Milliseconds()\n\tif IsGreaterThanOrEqual(v, s) && IsLessThan(v, t) && IsGreaterThanOrEqual(v, nil) {\n\t}\n');
    ok (ordered.includes ('(s == nil || (v != nil && *v >= *s))'), 'two *int64 keep the helper nil table: ' + ordered);
    ok (ordered.includes ('(v == nil || *v < t)'), 'a pointer against a `value` operand keeps the nil arm: ' + ordered);
    ok (ordered.includes ('IsGreaterThanOrEqual(v, nil)'), 'a nil operand stays a helper call: ' + ordered);
    const values = f ('\tvar n int64 = this.ParseToInt(p)\n\tvar i int = len("x")\n\tif IsEqual(n, 5) && IsGreaterThan(n, i) && IsLessThanOrEqual(n, 7) {\n\t}\n');
    ok (values.includes ('(n == 5)') && values.includes ('(n > int64(i))') && values.includes ('(n <= 7)'), 'value operands compare natively: ' + values);
    const truthy = f ('\tvar b bool = true\n\tvar pb *bool = this.SafeBool(p, "b")\n\tvar s string = this.SafeStringString(p)\n\tif EvalTruthy(b) && EvalTruthy(pb) && IsTrue(s) {\n\t}\n');
    ok (truthy.includes ('(b)') && truthy.includes ('(pb != nil && *pb)') && truthy.includes ('(s != "")'), 'truthiness on a proven operand: ' + truthy);
    // unprovable operands: byte-identical, no inline body
    const boxes = f ('\tvar a any = this.SafeValue(p, "a")\n\tvar b any = nil\n\tb = this.SafeString(p, "b")\n\tif IsEqual(a, nil) || IsEqual(b, "x") || IsEqual(a, "x") || IsGreaterThan(a, 2) {\n\t}\n');
    ok (boxes === head + 'func (this *X) F(p any) any {\n\tvar a any = this.SafeValue(p, "a")\n\tvar b any = nil\n\tb = this.SafeString(p, "b")\n\tif IsEqual(a, nil) || IsEqual(b, "x") || IsEqual(a, "x") || IsGreaterThan(a, 2) {\n\t}\n\treturn nil\n}\n', 'an any operand keeps the helper verbatim: ' + boxes);
    const shadow = f ('\tvar a *string = this.SafeString(p, "a")\n\tif true {\n\t\tvar a string = "x"\n\t\t_ = a\n\t}\n\tif IsEqual(a, "x") {\n\t}\n');
    ok (shadow.includes ('IsEqual(a, "x")'), 'a shadowed name keeps the helper: ' + shadow);
    const closure = f ('\tvar a *string = this.SafeString(p, "a")\n\t_ = func(a any) any {\n\t\tif IsEqual(a, nil) {\n\t\t\treturn a\n\t\t}\n\t\treturn nil\n\t}(a)\n');
    ok (closure.includes ('IsEqual(a, nil)'), 'a closure parameter shadows the declaration: ' + closure);
    const wide = f ('\tvar n int = this.ParseToInt(p)\n\tif IsEqual(n, 99999999999999999999) {\n\t}\n');
    ok (wide.includes ('IsEqual(n, 99999999999999999999)'), 'a literal wider than int keeps the helper: ' + wide);
    const floats = f ('\tvar f *float64 = this.SafeNumber(p, "f")\n\tvar g float64 = this.ParseFloat(p)\n\tif IsLessThan(f, g) && IsGreaterThan(f, g) {\n\t}\n');
    ok (floats.includes ('IsLessThan(f, g)'), 'float64 `<` keeps the helper (NaN): ' + floats);
    ok (floats.includes ('(f != nil && *f > g)'), 'float64 `>` is native: ' + floats);
    const fields = f ('\tif IsEqual(this.Outcomes, nil) && !IsEqual(this.ProxyUrl, nil) && IsEqual(this.Markets, nil) {\n\t}\n');
    ok (fields.includes ('this.Outcomes == nil') && fields.includes ('this.ProxyUrl != nil'), 'a proven container field nil-tests natively: ' + fields);
    ok (fields.includes ('IsEqual(this.Markets, nil)'), 'an unproven field keeps the helper: ' + fields);
    // hand-written files and a second application
    const hand = 'package ccxt\n\nfunc F(a *string, b *string) any {\n\treturn IsEqual(a, b)\n}\n';
    ok (hx10w2G04 (hand) === hand, 'a hand-written file is untouched');
    const once = hx10w2G04 (values);
    ok (hx10w2G04 (once) === once, 'a second application is a no-op');
    ok (!/func\s*\(\s*\)/.test (pair), 'no inline helper body emitted: ' + pair);
    return problems;
}
