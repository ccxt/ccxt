#!/usr/bin/env python3
"""
Generates java/lib/src/main/java/io/github/ccxt/TypedCores.java

Parses the `public T(Object raw)` constructors of the generated unified types in
java/lib/src/main/java/io/github/ccxt/types/*.java and, for every family whose
constructor is *mechanically invertible*, emits four helpers:

    public static T        toT(Object raw)         // null-safe, idempotent
    public static List<T>  toTList(Object raw)     // null-safe, element-wise
    public static Object   fromT(Object v)         // T -> Map (or List for tuples), pass-through otherwise
    public static Object   fromTList(Object v)     // List<T> -> List<Map>, pass-through otherwise

plus a single runtime dispatcher `fromTyped(Object)` that instanceof-chains over
every reversible family.

Invertibility is decided purely syntactically. Only these constructor line
shapes are understood (anything else makes the family non-invertible):

  1. Map<String, Object> data = TypeHelper.toMap(raw);                       (preamble)
  2. this.<f> = TypeHelper.<safeString|safeFloat|safeInteger|safeBool>(data, "<key>");
  3. this.<f> = TypeHelper.getInfo(data);
  4. this.<f> = TypeHelper.safeValue(data, "<key>");                          (opaque passthrough)
  5. nested object (2 lines) / nested list (4 lines)
  6. positional tuple: this.<f> = TypeHelper.<safeIntegerAt|safeFloatAt>(raw, <i>);

Invertibility is transitive: a family that nests a non-invertible family is
itself non-invertible.

Usage:
    python3 build/generateJavaTypedCoreHelpers.py                 # generate + report skips
    python3 build/generateJavaTypedCoreHelpers.py --capabilities  # JSON list of invertible families
    python3 build/generateJavaTypedCoreHelpers.py --check         # non-zero exit if output is stale

Stdlib only. Deterministic: everything is sorted by family name.
"""

import argparse
import glob
import json
import os
import re
import sys

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TYPES_DIR = os.path.join(REPO_ROOT, 'java', 'lib', 'src', 'main', 'java', 'io', 'github', 'ccxt', 'types')
OUT_PATH = os.path.join(REPO_ROOT, 'java', 'lib', 'src', 'main', 'java', 'io', 'github', 'ccxt', 'TypedCores.java')

HEADER = ('// PLEASE DO NOT EDIT THIS FILE, IT IS GENERATED AND WILL BE OVERWRITTEN:\n'
          '// https://github.com/ccxt/ccxt/blob/master/CONTRIBUTING.md#how-to-contribute-code\n'
          '// Generated by build/generateJavaTypedCoreHelpers.py\n')

# ---------------------------------------------------------------------------
# parsing
# ---------------------------------------------------------------------------

RE_PREAMBLE = re.compile(r'Map<String, Object> data = TypeHelper\.toMap\(raw\);')
# `this.__raw = raw;` retains the payload the type was projected from so that from*()
# can be an exact inverse rather than a lossy field-set rebuild. It carries no key of
# its own, so it is preamble for inversion purposes.
RE_RAW_RETAIN = re.compile(r'this\.__raw = raw;')
RE_SCALAR = re.compile(r'this\.(\w+) = TypeHelper\.(safeString|safeFloat|safeInteger|safeBool)\(data, "([^"]+)"\);')
RE_INFO = re.compile(r'this\.(\w+) = TypeHelper\.getInfo\(data\);')
RE_RAW = re.compile(r'this\.(\w+) = TypeHelper\.safeValue\(data, "([^"]+)"\);')
RE_AT = re.compile(r'this\.(\w+) = TypeHelper\.(safeIntegerAt|safeFloatAt)\(raw, (\d+)\);')
RE_NESTED_HEAD = re.compile(r'Object (\w+)Raw = TypeHelper\.safeValue\(data, "([^"]+)"\);')
# `data.containsKey("k") && data.get("k") != null ? new T(data.get("k")) : null`
# (Limits / NetworkLimits / CurrencyLimits). Mechanically the same field read as
# RE_NESTED_HEAD's ternary, so it is invertible under the same __raw rule.
RE_CONTAINS_KEY = re.compile(
    r'this\.(\w+) = data\.containsKey\("([^"]+)"\) && data\.get\("\2"\) != null '
    r'\? new (\w+)\(data\.get\("\2"\)\) : null;')
# `x = xRaw instanceof Map ? (Map<String, Object>) xRaw : null;` (OrderRequest.params)
RE_MAP_IF = re.compile(
    r'this\.(\w+) = (\w+)Raw instanceof Map \? \(Map<String, Object>\) \2Raw : null;')
# `if (xRaw instanceof Map<?, ?> xMap) { this.<f> = new LinkedHashMap<>(); for (...) put(k, new T(v)); }`
# (CurrencyInterface.networks / DepositWithdrawFee.networks -- a keyed bag of a
# single nested family, i.e. the container shape inline in an interface)
# `this.<field> = new LinkedHashMap<>();` opening a Dictionary-wrapper fill loop
RE_BAG_INIT = re.compile(r'this\.(\w+) = new LinkedHashMap<>\(\);')


class Unparseable(Exception):
    def __init__(self, reason):
        super().__init__(reason)
        self.reason = reason


def parse_ctor(name, src):
    """Return list of field dicts, or raise Unparseable."""
    m = re.search(r'\n    public ' + re.escape(name) + r'\(Object raw\) \{\n(.*?)\n    \}\n', src, re.S)
    if not m:
        raise Unparseable('no `public %s(Object raw)` constructor found' % name)
    lines = [l.strip() for l in m.group(1).split('\n')]
    lines = [l for l in lines if l and not l.startswith('//')]
    out = []
    i = 0
    while i < len(lines):
        l = lines[i]
        if RE_PREAMBLE.fullmatch(l) or RE_RAW_RETAIN.fullmatch(l):
            i += 1
            continue
        mm = RE_SCALAR.fullmatch(l)
        if mm:
            out.append({'field': mm.group(1), 'kind': 'scalar', 'key': mm.group(3)})
            i += 1
            continue
        mm = RE_INFO.fullmatch(l)
        if mm:
            out.append({'field': mm.group(1), 'kind': 'info', 'key': 'info'})
            i += 1
            continue
        mm = RE_RAW.fullmatch(l)
        if mm:
            out.append({'field': mm.group(1), 'kind': 'raw', 'key': mm.group(2)})
            i += 1
            continue
        mm = RE_AT.fullmatch(l)
        if mm:
            out.append({'field': mm.group(1), 'kind': 'at', 'index': int(mm.group(3))})
            i += 1
            continue
        # ---- container-bag shapes (Dictionary wrappers: Tickers, FundingRates, ...)
        # `this.<f> = new LinkedHashMap<>();` followed by a for-loop that fills it
        # from the payload's own entries. The loop is pure projection (every value
        # re-enters through the element family's own constructor), so from* must
        # return __raw -- the family is invertible ONLY when __raw is retained.
        mm = RE_BAG_INIT.fullmatch(l)
        if mm and i + 1 < len(lines) and lines[i + 1].startswith('for (Map.Entry<String, Object> entry : data.entrySet())'):
            f = mm.group(1)
            joined = '\n'.join(lines[i + 2:i + 6])
            m2 = re.match(
                r'if \(entry\.getValue\(\) instanceof List<\?> \w+\) \{\n'
                r'this\.' + f + r'\.put\(entry\.getKey\(\),\n'
                r'\(\(List<Object>\) \w+\)\.stream\(\)\.map\((\w+)::new\)\.collect\(Collectors\.toList\(\)\)\);\n'
                r'\}\n\}', joined)
            if m2:
                out.append({'field': f, 'kind': 'bag', 'key': f, 'of': m2.group(1), 'list': True})
                i += 6
                continue
            m2 = re.match(
                r'if \(!"info"\.equals\(entry\.getKey\(\)\)\) \{\n'
                r'this\.' + f + r'\.put\(entry\.getKey\(\), new (\w+)\(entry\.getValue\(\)\)\);\n'
                r'\}\n\}', joined)
            if m2:
                out.append({'field': f, 'kind': 'bag', 'key': f, 'of': m2.group(1), 'list': False})
                i += 6
                continue
            m2 = re.match(
                r'this\.' + f + r'\.put\(entry\.getKey\(\), new (\w+)\(entry\.getValue\(\)\)\);\n\}',
                '\n'.join(lines[i + 2:i + 4]))
            if m2:
                out.append({'field': f, 'kind': 'bag', 'key': f, 'of': m2.group(1), 'list': False})
                i += 4
                continue
        # `this.<f> = data.containsKey("k") && data.get("k") != null ? new T(...)` (Limits & co)
        mm = RE_CONTAINS_KEY.fullmatch(l)
        if mm:
            out.append({'field': mm.group(1), 'kind': 'nested', 'key': mm.group(2), 'of': mm.group(3)})
            i += 1
            continue
        # `this.<f> = xRaw instanceof Map ? (Map<String, Object>) xRaw : null;`
        # (OrderRequest.params -- a passthrough of the preceding safeValue line)
        if i > 0:
            prev = lines[i - 1]
            pm = RE_RAW.fullmatch(prev)
            mm = RE_MAP_IF.fullmatch(l)
            if mm and pm and pm.group(2) == 'params':
                out.append({'field': mm.group(1), 'kind': 'raw', 'key': 'params'})
                i += 1
                continue
        mm = RE_NESTED_HEAD.fullmatch(l)
        if mm and i + 1 < len(lines):
            f, key = mm.group(1), mm.group(2)
            nxt = lines[i + 1]
            m2 = re.fullmatch(r'this\.' + f + r' = ' + f + r'Raw != null \? new (\w+)\(' + f + r'Raw\) : null;', nxt)
            if m2:
                out.append({'field': f, 'kind': 'nested', 'key': key, 'of': m2.group(1)})
                i += 2
                continue
            # inline keyed bag: `if (xRaw instanceof Map<?, ?> xMap) { this.<f> = new
            # LinkedHashMap<>(); for (...) { put(k, new T(v)); } }` (CurrencyInterface.networks /
            # DepositWithdrawFee.networks). Consumes the head line too, so no 'raw'
            # field is recorded for the head itself.
            m2 = re.fullmatch(r'if \(' + f + r'Raw instanceof Map<\?, \?> \w+\) \{', nxt)
            if m2 and i + 7 < len(lines):
                blk = '\n'.join(lines[i + 2:i + 8])
                m3 = re.fullmatch(
                    r'this\.' + f + r' = new LinkedHashMap<>\(\);\n'
                    r'for \(Map\.Entry<String, Object> entry : \(\(Map<String, Object>\) \w+\)\.entrySet\(\)\) \{\n'
                    r'this\.' + f + r'\.put\(entry\.getKey\(\), new (\w+)\(entry\.getValue\(\)\)\);\n'
                    r'\}\n\}', blk)
                if m3:
                    out.append({'field': f, 'kind': 'bag', 'key': key, 'of': m3.group(1), 'list': False})
                    i += 7
                    continue
            m2 = re.fullmatch(r'if \(' + f + r'Raw instanceof List<\?> (\w+)\) \{', nxt)
            if m2 and i + 3 < len(lines):
                m3 = re.fullmatch(
                    r'this\.' + f + r' = \(\(List<Object>\) ' + m2.group(1) +
                    r'\)\.stream\(\)\.map\((\w+)::new\)\.collect\(Collectors\.toList\(\)\);', lines[i + 2])
                if m3 and lines[i + 3] == '}':
                    out.append({'field': f, 'kind': 'nestedlist', 'key': key, 'of': m3.group(1)})
                    i += 4
                    continue
        raise Unparseable('unrecognised constructor line: %s' % l)
    if not out:
        raise Unparseable('constructor assigns no fields')
    positional = [f for f in out if f['kind'] == 'at']
    if positional and len(positional) != len(out):
        raise Unparseable('mixes positional-tuple and map-keyed fields')
    return out


RE_FINAL_RAW = re.compile(r'\n    public final Object __raw;\n')


def load_families():
    """Returns (parsed, raw_only, skipped).

    parsed   : name -> field list; from* returns __raw and carries a field-rebuild
               fallback for a type constructed without a payload.
    raw_only : name -> reason; the constructor is hand-written / bespoke and cannot
               be parsed, but the class declares `public final Object __raw`. javac
               already proves a final field is assigned on EVERY constructor path, so
               `from*` = `__raw` is total without parsing a single field line. This is
               what makes the dictionary containers (Balances, OrderBook) and the
               inline-bag interfaces invertible: their projection is lossy, the
               retained payload is not.
    skipped  : name -> reason; neither parseable nor carrying a final __raw.
    """
    parsed, raw_only, skipped = {}, {}, {}
    for path in sorted(glob.glob(os.path.join(TYPES_DIR, '*.java'))):
        name = os.path.basename(path)[:-5]
        if name == 'TypeHelper':
            continue
        with open(path, encoding='utf-8') as fh:
            src = fh.read()
        try:
            parsed[name] = parse_ctor(name, src)
        except Unparseable as exc:
            if RE_FINAL_RAW.search(src) and re.search(r'\n    public ' + re.escape(name) + r'\(Object raw\) \{\n', src):
                raw_only[name] = exc.reason
            else:
                skipped[name] = exc.reason
    return parsed, raw_only, skipped


def compute_invertible(parsed, raw_only, skipped):
    """Transitive closure: a family nesting a non-invertible family is non-invertible.

    raw_only families nest nothing we can see (their constructor is opaque), but
    they do not need to: from* hands back __raw, never a rebuilt nested value.
    """
    bad = dict(skipped)
    changed = True
    while changed:
        changed = False
        for name in sorted(parsed):
            if name in bad:
                continue
            for f in parsed[name]:
                if f['kind'] in ('nested', 'nestedlist'):
                    dep = f['of']
                    if dep in bad:
                        bad[name] = 'nests non-invertible family %s (field `%s`)' % (dep, f['field'])
                        changed = True
                        break
                    if dep not in parsed and dep not in raw_only:
                        bad[name] = 'nests unknown family %s (field `%s`)' % (dep, f['field'])
                        changed = True
                        break
    inv = sorted(n for n in list(parsed) + list(raw_only) if n not in bad)
    return inv, bad


