def emit_family(name, fields):
    """fields is None for a raw-only family (opaque constructor, from* = __raw only)."""
    positional = bool(fields) and fields[0]['kind'] == 'at'
    L = []
    L.append('    // ---- %s ----' % name)
    L.append('')
    L.append('    public static %s to%s(Object raw) {' % (name, name))
    L.append('        if (raw == null) {')
    L.append('            return null;')
    L.append('        }')
    L.append('        if (raw instanceof %s already) {' % name)
    L.append('            return already;')
    L.append('        }')
    L.append('        return new %s(raw);' % name)
    L.append('    }')
    L.append('')
    L.append('    public static List<%s> to%sList(Object raw) {' % (name, name))
    L.append('        if (!(raw instanceof List<?> list)) {')
    L.append('            return null;')
    L.append('        }')
    L.append('        List<%s> out = new ArrayList<>(list.size());' % name)
    L.append('        for (Object element : list) {')
    L.append('            out.add(to%s(element));' % name)
    L.append('        }')
    L.append('        return out;')
    L.append('    }')
    L.append('')
    L.append('    public static Object from%s(Object value) {' % name)
    L.append('        if (!(value instanceof %s typed)) {' % name)
    L.append('            return value;')
    L.append('        }')
    L.append('        // Exact inverse: hand back the very payload the type was built from.')
    L.append('        // Reconstructing from the declared fields is NOT an inverse -- the type is a')
    L.append('        // fixed-shape projection of a variable-shape payload, so it would drop venue')
    L.append('        // extras and invent nulls for keys that were never present.')
    L.append('        if (typed.__raw != null) {')
    L.append('            return typed.__raw;')
    L.append('        }')
    if fields is None:
        L.append('        // Opaque (hand-written) constructor: __raw is final and therefore assigned')
        L.append('        // on every construction path, so it is only null when the payload itself was')
        L.append('        // null. There is no field set to rebuild from; hand the value back as-is.')
        L.append('        return value;')
    elif positional:
        L.append('        // Positional tuple: the constructor reads by index off a bare List and')
        L.append('        // widens every slot to Long/Double, so rebuilding from the parsed fields')
        L.append('        // is only a fallback for a type constructed without a payload -- it would')
        L.append('        // turn an integer volume of 2 back into 2.0.')
        L.append('        List<Object> out = new ArrayList<>();')
        by_index = {f['index']: f for f in fields}
        for idx in range(max(by_index) + 1):
            f = by_index.get(idx)
            if f is None:
                L.append('        out.add(null); // index %d unused by the constructor' % idx)
            else:
                L.append('        out.add(typed.%s);' % f['field'])
        L.append('        return out;')
    else:
        L.append('        // nulls are PUT rather than omitted: the constructor reads every key via')
        L.append('        // safe* accessors, so a present-but-null key and an absent key are')
        L.append('        // indistinguishable on the way back in. Putting them keeps the key set')
        L.append('        // stable, which is what round-trip callers compare on.')
        L.append('        Map<String, Object> out = new LinkedHashMap<>();')
        for f in fields:
            if f['kind'] in ('scalar', 'info', 'raw'):
                L.append('        out.put("%s", typed.%s);' % (f['key'], f['field']))
            elif f['kind'] == 'nested':
                L.append('        out.put("%s", from%s(typed.%s));' % (f['key'], f['of'], f['field']))
            elif f['kind'] == 'nestedlist':
                L.append('        out.put("%s", from%sList(typed.%s));' % (f['key'], f['of'], f['field']))
        L.append('        return out;')
    L.append('    }')
    L.append('')
    L.append('    public static Object from%sList(Object value) {' % name)
    L.append('        if (!(value instanceof List<?> list)) {')
    L.append('            return value;')
    L.append('        }')
    L.append('        List<Object> out = new ArrayList<>(list.size());')
    L.append('        for (Object element : list) {')
    L.append('            out.add(from%s(element));' % name)
    L.append('        }')
    L.append('        return out;')
    L.append('    }')
    L.append('')
    return L


def emit(inv, parsed, raw_only):
    L = []
    L.append(HEADER.rstrip('\n'))
    L.append('')
    L.append('package io.github.ccxt;')
    L.append('')
    L.append('import java.util.ArrayList;')
    L.append('import java.util.LinkedHashMap;')
    L.append('import java.util.List;')
    L.append('import java.util.Map;')
    L.append('')
    L.append('import io.github.ccxt.types.*;')
    L.append('')
    L.append('/**')
    L.append(' * Typed cores: bidirectional bridges between the unified type classes and the')
    L.append(' * raw Object/Map/List representation used by the transpiled exchange cores.')
    L.append(' * Only families whose (Object raw) constructor is mechanically invertible are')
    L.append(' * represented here (%d of %d families; %d of them hand-written with an opaque' % (len(inv), len(parsed) + len(raw_only), len(raw_only)))
    L.append(' * constructor and a final __raw, whose inverse is the retained payload alone).')
    L.append(' */')
    L.append('public final class TypedCores {')
    L.append('')
    L.append('    private TypedCores() {}')
    L.append('')
    for name in inv:
        L.extend(emit_family(name, parsed.get(name)))
    # ---- snapshot cores (build/javaTypedCores.ts SNAPSHOT_CORES) ----
    # A watch* order-book core hands back the LIVE ws book that the WsClient thread
    # keeps mutating. The wrapper used to snapshot it (`new OrderBook(res)` copies the
    # sides); once the core is typed the snapshot has to live on the core itself.
    # Java analogue of C#'s BaseExchange.ToOrderBookSnapshot (ccxt/ccxt#30110).
    # Idempotent by contract: a core whose tail is itself a typed watchOrderBook
    # override joins an already-copied book, and copying twice is harmless.
    L.append('    // ---- snapshot cores ----')
    L.append('')
    L.append('    /**')
    L.append('     * Snapshot of a live ws order book. The core hands back the book the WsClient')
    L.append('     * thread keeps applying deltas to; a caller holding it would see updates it')
    L.append('     * must not see, so the copy moves onto the core return. Pass-through for')
    L.append('     * anything that is not a WsOrderBook (a not-supported stub throws before')
    L.append('     * reaching here; a plain map is handed back unchanged).')
    L.append('     */')
    L.append('    public static io.github.ccxt.ws.WsOrderBook toOrderBookSnapshot(Object raw) {')
    L.append('        if (raw instanceof io.github.ccxt.ws.WsOrderBook book) {')
    L.append('            return book.copy();')
    L.append('        }')
    L.append('        return null;')
    L.append('    }')
    L.append('')
    # dispatcher
    L.append('    // ---- runtime dispatcher ----')
    L.append('')
    L.append('    /**')
    L.append('     * Converts any typed value (or list of typed values) back into its raw')
    L.append('     * Map/List representation. Anything that is not a reversible family is')
    L.append('     * returned unchanged.')
    L.append('     */')
    L.append('    public static Object fromTyped(Object value) {')
    L.append('        if (value == null) {')
    L.append('            return null;')
    L.append('        }')
    for name in inv:
        L.append('        if (value instanceof %s) {' % name)
        L.append('            return from%s(value);' % name)
        L.append('        }')
    L.append('        if (value instanceof List<?> list) {')
    L.append('            List<Object> out = new ArrayList<>(list.size());')
    L.append('            for (Object element : list) {')
    L.append('                out.add(fromTyped(element));')
    L.append('            }')
    L.append('            return out;')
    L.append('        }')
    L.append('        return value;')
    L.append('    }')
    L.append('}')
    L.append('')
    return '\n'.join(L)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--capabilities', action='store_true', help='print invertible families as JSON and exit')
    ap.add_argument('--check', action='store_true', help='verify the checked-in output is up to date')
    args = ap.parse_args()

    parsed, raw_only, skipped = load_families()
    inv, bad = compute_invertible(parsed, raw_only, skipped)
    source = emit(inv, parsed, raw_only)

    if args.capabilities:
        print(json.dumps({'count': len(inv), 'families': inv}, indent=2))
        return 0

    total = len(parsed) + len(raw_only) + len(skipped)
    print('scanned %d type classes in %s' % (total, os.path.relpath(TYPES_DIR, REPO_ROOT)))
    print('invertible families: %d' % len(inv))
    print('  of which raw-only (opaque ctor, final __raw): %d' % len(raw_only))
    for name in sorted(raw_only):
        print('  RAW  %-28s %s' % (name, raw_only[name]))
    print('SKIPPED %d families:' % len(bad))
    for name in sorted(bad):
        print('  SKIP %-28s %s' % (name, bad[name]))

    rel = os.path.relpath(OUT_PATH, REPO_ROOT)
    existing = None
    if os.path.exists(OUT_PATH):
        with open(OUT_PATH, encoding='utf-8') as fh:
            existing = fh.read()
    if args.check:
        if existing != source:
            print('STALE: %s does not match the generator output' % rel, file=sys.stderr)
            return 1
        print('up to date: %s' % rel)
        return 0
    if existing == source:
        print('unchanged: %s' % rel)
    else:
        with open(OUT_PATH, 'w', encoding='utf-8') as fh:
            fh.write(source)
        print('wrote: %s (%d lines)' % (rel, source.count('\n') + 1))
    return 0


if __name__ == '__main__':
    sys.exit(main())
