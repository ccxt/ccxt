import * as fs from 'fs';
import * as path from 'path';
import execSync from 'child_process';
import log from 'ololog'
import { isWindows } from './../ts/src/base/functions/platform.js';

const WS_SUPPORT = true; // set to true when WS support is added


const dirSep = isWindows ? '\\' : '/';

const foldersToSearch = [
    `./go/v4`
];

const filesToDelete =[
    `./go/tests/base/test.structs.go`,
    `./go/tests/base/test.types.rest.go`,
    `./go/tests/base/test.types.pro.go`
]

const whiteListFolders = [
    `go${dirSep}v4${dirSep}protoc`,
    // keep all prediction exchange files: the Transpile prediction to Go workflow step
    // force-regenerates every prediction core from ts and would resurrect cores whose
    // deleted implicit api files nothing regenerates, see https://github.com/ccxt/ccxt/pull/29696
    `go${dirSep}v4${dirSep}prediction`
]


function capitalizeFirstLetter(string: string) {
    return string.charAt(0).toUpperCase() + string.slice(1);
}

function deleteFilesRecursively(directory: string, exchangesToKeep: string[]): void {
    if (!fs.existsSync(directory)) {
        console.warn(`Directory not found: ${directory}`);
        return;
    }

    fs.readdirSync(directory).forEach(file => {
        const fullPath = path.join(directory, file);

        const fileWithoutExt = path.parse(file).name;

        const fileExtension = path.extname(file);
        if (fileExtension !== '.go' && !fs.statSync(fullPath).isDirectory()) {
            return; // Skip non-Go files
        }

        if (file.startsWith('exchange')) {
            return; // Always keep exchange.go and exchange_X.go files
        }

        if (whiteListFolders.some(folder => fullPath.startsWith(folder) || fullPath.startsWith (`.${dirSep}${folder}`))) {
            return; // Always keep files in whitelisted folders
        }

        if (fs.statSync(fullPath).isDirectory()) {
            deleteFilesRecursively(fullPath, exchangesToKeep);
        } else if (!exchangesToKeep.some(exchange => (fileWithoutExt === exchange || fileWithoutExt.startsWith(exchange + '_')))) {
            try {
                fs.unlinkSync(fullPath);
                log.red(`Deleted: ${fullPath}`);
            } catch (error) {
                log.red(`Failed to delete ${fullPath}:`, error);
            }
        }
    });
}

function createExchangeDynamicFile(exchanges: string[], ws = false, prediction = false) {

    const dynamicPath = prediction ? './go/v4/prediction/exchange_dynamic.go' : (ws ? './go/v4/pro/exchange_dynamic.go' : './go/v4/exchange_dynamic.go');

    const pack = prediction ? 'ccxtprediction' : (ws ? 'ccxtpro' : 'ccxt');
    const imports = (ws || prediction) ? 'import ccxt "github.com/ccxt/ccxt/go/v4"' : ''
    const prefix = (ws || prediction) ? 'ccxt.' : '';

    const caseStatements = exchanges.map(exchange => {
        const statement = `\tcase "${exchange}":
\t\t${exchange}Itf := New${capitalizeFirstLetter(exchange)}(exchangeArgs)
\t\treturn ${exchange}Itf, true`;
        if (prediction) {
            return fs.existsSync('./ts/src/prediction/' + exchange + '.ts') ? statement : '';
        }
        if (!ws) {
            // prediction-only exchanges (e.g. kalshi) don't exist in the ccxt package — keep
            // only ids with a regular source; ids in both (e.g. hyperliquid) land in both files
            return fs.existsSync('./ts/src/' + exchange + '.ts') ? statement : '';
        }
        return fs.existsSync('./ts/src/pro/' + exchange + '.ts') ? statement : '';
        }).filter(statement => statement !== '').join('\n');

const ExchangeStatement = `\tcase "Exchange":
		ExchangeItf := &Exchange{}
		ExchangeItf.Init(exchangeArgs)
		return ExchangeItf, true
`


    const template =`
package ${pack}

${imports ? imports + '\n\n' : ''}// PLEASE DO NOT EDIT THIS FILE, IT IS GENERATED AND WILL BE OVERWRITTEN:
// https://github.com/ccxt/ccxt/blob/master/CONTRIBUTING.md#how-to-contribute-code

func DynamicallyCreateInstance(exchangeId string, exchangeArgs map[string]any) (${prefix}ICoreExchange, bool) {
\tswitch exchangeId {
${(ws || prediction) ? '' : ExchangeStatement}${caseStatements ? caseStatements + '\n' : ''}\tdefault:
\t\treturn nil, false
\t}
}`

    fs.writeFileSync(dynamicPath, template.trim() + '\n');
    log.green(`Created: ${dynamicPath}`);
}


function createExchangeTypedInterfaceFile(exchanges: string[]) {

    const path = './go/v4/exchange_typed_interface.go'

    const fileContent = fs.readFileSync(path, 'utf-8');

    const regex = /(type IExchange interface {(\n|.)+\n}[\n]+)func CreateExchange/

    const interfaceMatch = fileContent.match(regex) as RegExpMatchArray;

    // Modify the file content as needed

    const caseStatements = exchanges.map(exchange => fs.existsSync('./ts/src/' + exchange + '.ts') ? `\tcase "${exchange}":
\t\titf := New${capitalizeFirstLetter(exchange)}(options)
\t\treturn itf` : '').filter(statement => statement !== '').join('\n');

    const template = `
package ccxt

import "strings"

// PLEASE DO NOT EDIT THIS FILE, IT IS GENERATED AND WILL BE OVERWRITTEN:
// https://github.com/ccxt/ccxt/blob/master/CONTRIBUTING.md#how-to-contribute-code

${interfaceMatch[1].trimEnd()}

func CreateExchange(exchangeId string, options map[string]any) IExchange {
\texchangeId = strings.ToLower(exchangeId)
\tswitch exchangeId {
\tcase "exchange":
\t\titf := NewExchangeTyped(nil)
\t\treturn itf
${caseStatements ? caseStatements + '\n' : ''}\tdefault:
\t\treturn nil
\t}
}
`
    fs.writeFileSync(path, template.trim() + '\n');
}


function createWsExchangeTypedInterfaceFile(exchanges: string[]) {

    const path = './go/v4/pro/exchange_typed_interface.go'

    const interfaceWs = [
            'type IExchange interface {',
            '\tccxt.IExchange',
            '}'
        ].join('\n');

    const caseStatements = exchanges.map(exchange => {
        return fs.existsSync('./ts/src/pro/' + exchange + '.ts') ? `\tcase "${exchange}":
\t\titf := New${capitalizeFirstLetter(exchange)}(options)
\t\treturn itf` : ''}).filter(statement => statement !== '').join('\n');

    const template = `
package ccxtpro

import (
\t"strings"

\tccxt "github.com/ccxt/ccxt/go/v4"
)

// PLEASE DO NOT EDIT THIS FILE, IT IS GENERATED AND WILL BE OVERWRITTEN:
// https://github.com/ccxt/ccxt/blob/master/CONTRIBUTING.md#how-to-contribute-code

${interfaceWs}

func CreateExchange(exchangeId string, options map[string]any) ccxt.IExchange {
\texchangeId = strings.ToLower(exchangeId)
\tswitch exchangeId {
${caseStatements ? caseStatements + '\n' : ''}\tdefault:
\t\treturn nil
\t}
}
`
    fs.writeFileSync(path, template.trim() + '\n');
}


function transpileAndGenerateAPI(exchanges: string[]) {
    execSync.execSync(`tsx ./build/generateImplicitAPI.ts`, { stdio: 'inherit' });
    for (const exchange of exchanges) {
        execSync.execSync(`tsx ./build/goTranspiler.ts ${exchange}`, { stdio: 'inherit' });
        const WS_EXISTED = fs.existsSync('./ts/src/pro/' + exchange + '.ts');
        if (WS_SUPPORT && WS_EXISTED) {
            execSync.execSync(`tsx ./build/goTranspiler.ts ${exchange} --ws`, { stdio: 'inherit' });
        }
    }

}

function main() {
    const argsRaw = process.argv.slice(2);

    if (argsRaw.length < 1) {
        console.error("Usage: tsx granular-go-build.ts <exchange1> <exchange2> ...");
        process.exit(1);
    }
    const args = [...new Set(argsRaw)];
    transpileAndGenerateAPI(args)
    foldersToSearch.forEach(folder => deleteFilesRecursively(folder, args));
    createExchangeDynamicFile(args);
    if (WS_SUPPORT) {
        createExchangeDynamicFile(args, true);
    }
    createExchangeDynamicFile(args, false, true); // prediction exchanges (go/v4/prediction)
    createExchangeTypedInterfaceFile(args);
    createWsExchangeTypedInterfaceFile(args);

    for (const filePath of filesToDelete) {
        if (fs.existsSync(filePath)) {
            try {
                fs.unlinkSync(filePath);
                log.red(`Deleted: ${filePath}`);
            } catch (error) {
                log.red(`Failed to delete ${filePath}:`, error);
            }
        }
    }
    const languageSpecificFile = './go/tests/base/test.languageSpecific.go';
    if (fs.existsSync(languageSpecificFile)) {
        let fileContent = fs.readFileSync(languageSpecificFile, 'utf-8');
        const regex = /^[\t ]*TestStructs\(\);?[\t ]*(?:\r?\n|$)/m;
        fileContent = fileContent.replace(regex, '');
        fs.writeFileSync(languageSpecificFile, fileContent);
        log.green(`Modified: ${languageSpecificFile}`);
    }

    log.bright.cyan("Done! You can now build the Go project (tests/cli/etc) with 'go build' command.");
}

main();
