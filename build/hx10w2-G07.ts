// hx10w2 G07 — ParseInt over a nullable AsyncResult value: nil-guarded deref when the async element is *int64.

const G07_BASE_ASYNC_TYPES: Record<string, string> = { FetchTimeAsync: '*int64' };  // exchange_generated.go

function g07ReceiveType (file: string, method: string): string | undefined {
    const sig = new RegExp ('func \\(this \\*\\w+\\) ' + method + '\\([^)]*\\) <-chan AsyncResult\\[([^\\]\\n]+)\\]').exec (file);
    if (sig !== null) {
        return sig[1].trim ();
    }
    return G07_BASE_ASYNC_TYPES[method];
}

function g07WritesName (body: string, name: string): boolean {
    const rebind = new RegExp ('(?<![\\w.])' + name + '\\s*(?:[-+*/%|&^]?=(?!=)|\\+\\+|--|:=)', 'g');
    return rebind.test (body) || new RegExp ('&' + name + '\\b').test (body);
}

function g07Func (fn: string, file: string): string {
    if (fn.indexOf ('ParseInt(') < 0) {
        return fn;
    }
    const lines = fn.split ('\n');
    const proven = new Map<string, string> ();
    for (const line of lines) {
        const m = /^\s*([A-Za-z_]\w*) := <-this\.([A-Za-z_]\w*)\(/.exec (line);
        if (m === null) {
            continue;
        }
        const t = g07ReceiveType (file, m[2]);
        if (t !== undefined) {
            proven.set (m[1], t);
        }
    }
    if (proven.size === 0) {
        return fn;
    }
    for (let k = 0; k < lines.length; k++) {
        const m = /^(\t*)var ([A-Za-z_]\w*) int64 = (?:ccxt\.)?ParseInt\(([A-Za-z_]\w*)\.Value\)$/.exec (lines[k]);
        if (m === null) {
            continue;
        }
        const ind = m[1];
        const target = m[2];
        const recv = m[3];
        if (proven.get (recv) !== '*int64') {
            continue;
        }
        // the receive must be the only write: a rebind could install another AsyncResult
        const others = lines.filter ((l, i) => (i !== k) && !new RegExp ('^\\s*' + recv + ' := <-this\\.').test (l));
        if (g07WritesName (others.join ('\n'), recv)) {
            continue;
        }
        lines[k] = ind + 'var ' + target + ' int64 = 0\n'
            + ind + 'if ' + recv + '.Value != nil {\n'
            + ind + '\t' + target + ' = *' + recv + '.Value\n'
            + ind + '}';
    }
    return lines.join ('\n');
}

export function emitHx10w2G07Native (content: string): string {
    if (content.indexOf ('ParseInt(') < 0) {
        return content;
    }
    const parts = content.split (/(?=^func )/m);
    return parts.map ((part) => ((part.startsWith ('func ') ? g07Func (part, content) : part))).join ('');
}

export function hx10w2G07SelfCheck (): string[] {
    const problems: string[] = [];
    const ok = (cond: boolean, msg: string) => { if (!cond) { problems.push ('hx10w2 G07: ' + msg); } };
    const head = 'package ccxt\n\n// PLEASE DO NOT EDIT THIS FILE, IT IS GENERATED AND WILL BE OVERWRITTEN:\n\n';
    const sig = (t: string) => 'func (this *X) FetchTimeAsync(optionalArgs ...any) <-chan AsyncResult[' + t + '] {\n\tch := make(chan AsyncResult[' + t + '])\n\treturn ch\n}\n';
    const wrap = (t: string, body = 'var res int64 = ParseInt(r.Value)') => head + sig (t)
        + 'func (this *X) FetchTime(params ...any) (int64, error) {\n\tr := <-this.FetchTimeAsync(params...)\n\tif r.Err != nil {\n\t\treturn -1, r.Err\n\t}\n\t' + body + '\n\treturn res, nil\n}\n';
    const run = (content: string) => emitHx10w2G07Native (content);
    const good = run (wrap ('*int64'));
    ok (good.includes ('\tvar res int64 = 0\n\tif r.Value != nil {\n\t\tres = *r.Value\n\t}'), 'nil-guarded deref: ' + good);
    ok (!good.includes ('ParseInt('), 'helper gone');
    ok (good.includes ('return -1, r.Err'), 'sibling lines untouched');
    ok (run (wrap ('*string')) === wrap ('*string'), 'string element keeps the helper');
    ok (run (wrap ('int64')) === wrap ('int64'), 'non-pointer element keeps the helper');
    const nosig = head + 'func (this *X) FetchThing(params ...any) (int64, error) {\n\tr := <-this.FetchThingAsync(params...)\n\tvar res int64 = ParseInt(r.Value)\n\treturn res, nil\n}\n';
    ok (run (nosig) === nosig, 'unknown async core keeps the helper');
    const rebound = wrap ('*int64').replace ('\tvar res int64', '\tr = <-this.FetchTimeAsync(params...)\n\tvar res int64');
    ok (run (rebound) === rebound, 'rebound receive keeps the helper');
    const stray = head + sig ('*int64') + 'func (this *X) FetchTime(params ...any) (int64, error) {\n\tvar res int64 = ParseInt(q.Value)\n\treturn res, nil\n}\n';
    ok (run (stray) === stray, 'unproven receiver keeps the helper');
    const wrappers = head + 'func (this *BaseExchange) FetchTime(params ...any) (int64, error) {\n\tr := <-this.FetchTimeAsync(params...)\n\tvar res int64 = ParseInt(r.Value)\n\treturn res, nil\n}\n';
    ok (run (wrappers).includes ('res = *r.Value'), 'base tier FetchTimeAsync is in the table');
    ok (run (good) === good, 'idempotent');
    return problems;
}
