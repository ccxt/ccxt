// ===== hx10 wave10 GP24: the stdlib import seam for the two generated Go base files =====
// exchange_generated.go and exchange_prediction.go are assembled from a transpiled body spliced in
// after their header, so a printSourceFileStatements import is cut off and the printer keeps every
// stdlib call there. This module adds each package the spliced body really references and answers
// the transpiler's placeability question (goBaseFileStdlibImportSeam).

import fs from 'fs';
import path from 'path';
import { hx4G36AddImport } from './go-native-arith.js';

const GP24_HEADER = '// https://github.com/ccxt/ccxt/blob/master/CONTRIBUTING.md#how-to-contribute-code';
const GP24_BANNER = 'IT IS GENERATED AND WILL BE OVERWRITTEN';
// the two packages the native `.toString()` arms and the native string ops emit
const GP24_PACKAGES = [ 'strconv', 'strings' ];

// blank every string literal and comment, so a package named in text never counts as a use
function gp24MaskCode (content: string): string {
    return content
        .replace (/`[^`]*`/g, (m) => m.replace (/[^\n]/g, ' '))
        .replace (/"(?:[^"\\\n]|\\.)*"/g, (m) => ' '.repeat (m.length))
        .replace (/\/\*[\s\S]*?\*\//g, (m) => m.replace (/[^\n]/g, ' '))
        .replace (/\/\/[^\n]*/g, (m) => ' '.repeat (m.length));
}

// a real selector use on a code line: a comment or a string literal naming the package must not
// declare an unused import (go build rejects it)
function gp24UsesPackage (content: string, pkg: string): boolean {
    return new RegExp ('\\b' + pkg + '\\.[A-Z]\\w*\\s*\\(').test (gp24MaskCode (content));
}

export function hx10w10GP24BaseImports (content: string): string {
    if ((content.indexOf (GP24_BANNER) < 0) || (content.indexOf (GP24_HEADER) < 0)) {
        return content;
    }
    let text = content;
    for (const pkg of GP24_PACKAGES) {
        if (gp24UsesPackage (text, pkg)) {
            text = hx4G36AddImport (text, pkg);
        }
    }
    return text;
}

// the printer may only emit a stdlib call in the two base files whose writer declares the import
export function installHx10w10GP24BaseImportSeam (go: any): void {
    if (go !== undefined) {
        go.goBaseFileStdlibImportSeamPaths = /(?:base\/Exchange(?:\.nooverloads\.\d+)?|base\/PredictionExchange)\.ts$/;
    }
}

// A generated file can lose the text an import was declared for: the base-test rewrites delete
// sections after printing. Drop the packages the final body never names, or `go build` reports
// "imported and not used". Only the two packages this unit emits are ever dropped.
export function hx10w10GP24PruneImports (content: string): string {
    if (content.indexOf (GP24_BANNER) < 0) {
        return content; // hand-maintained files are never touched
    }
    const code = gp24MaskCode (content);
    const lines = content.split ('\n');
    const drop = new Set<number> ();
    for (let i = 0; i < lines.length; i++) {
        const match = /^import "([^"]+)"$/.exec (lines[i].trim ());
        if (match === null) {
            continue;
        }
        const importPath = match[1];
        const pkg = importPath.includes ('/') ? importPath.substring (importPath.lastIndexOf ('/') + 1) : importPath;
        if (!GP24_PACKAGES.includes (pkg)) {
            continue;
        }
        if (new RegExp ('\\b' + pkg + '\\.[A-Za-z_]').test (code)) {
            continue;
        }
        drop.add (i);
        if ((i + 1 < lines.length) && (lines[i + 1].trim () === '')) {
            drop.add (i + 1);
        }
    }
    if (drop.size === 0) {
        return content;
    }
    return lines.filter ((_line, index) => !drop.has (index)).join ('\n');
}

const GP24_HEAD =
    'package ccxt\n\n' +
    '// PLEASE DO NOT EDIT THIS FILE, IT IS GENERATED AND WILL BE OVERWRITTEN:\n' +
    GP24_HEADER + '\n\n';

export function hx10w10GP24Check (): string[] {
    const problems: string[] = [];
    const body = (lines: string) => GP24_HEAD + 'func (this *K) F() any {\n' + lines + '\n}\n';
    // a strconv emission declares the package after the generated header
    const itoa = hx10w10GP24BaseImports (body ('\tvar n int = GetArrayLength(a)\n\treturn strconv.Itoa(n)'));
    if (!itoa.includes ('\nimport "strconv"\n')) {
        problems.push ('hx10w10 GP24: strconv import not added: ' + itoa);
    }
    if (itoa.indexOf ('import "strconv"') < itoa.indexOf (GP24_HEADER)) {
        problems.push ('hx10w10 GP24: strconv import precedes the header: ' + itoa);
    }
    if (hx10w10GP24BaseImports (itoa) !== itoa) {
        problems.push ('hx10w10 GP24: second run is not idempotent: ' + itoa);
    }
    // the native string call declares strings
    const join = hx10w10GP24BaseImports (body ('\tvar ids []string = nil\n\treturn "[" + strings.Join(ids, ", ") + "]"'));
    if (!join.includes ('\nimport "strings"\n')) {
        problems.push ('hx10w10 GP24: strings import not added: ' + join);
    }
    // no stdlib use: byte-identical, and a mention in a comment or a literal adds nothing
    const plain = body ('\treturn ToString(a)');
    if (hx10w10GP24BaseImports (plain) !== plain) {
        problems.push ('hx10w10 GP24: a helper-only body changed: ' + hx10w10GP24BaseImports (plain));
    }
    const commented = body ('\t// strconv.Itoa(n) would go here\n\treturn "strings.Join(x, y)"');
    if (hx10w10GP24BaseImports (commented) !== commented) {
        problems.push ('hx10w10 GP24: a comment or literal declared an import: ' + hx10w10GP24BaseImports (commented));
    }
    // a hand-maintained file without the banner is never touched
    const raw = 'package ccxt\n\nfunc f () {}\n';
    if (hx10w10GP24BaseImports (raw) !== raw) {
        problems.push ('hx10w10 GP24: an unbannered file changed');
    }
    // the seam flag is what the printer reads: the two base sources only, never a sliced writer's
    const go: any = {};
    installHx10w10GP24BaseImportSeam (go);
    const seam = go.goBaseFileStdlibImportSeamPaths;
    if (!(seam instanceof RegExp)) {
        problems.push ('hx10w10 GP24: the seam paths were not installed');
    } else {
        if (!seam.test ('ts/src/base/Exchange.ts') || !seam.test ('ts/src/base/Exchange.nooverloads.42.ts') || !seam.test ('ts/src/base/PredictionExchange.ts')) {
            problems.push ('hx10w10 GP24: the seam misses a base source');
        }
        if (seam.test ('ts/src/test/base/test.cache.ts') || seam.test ('ts/src/test/base/test.orderBook.ts') || seam.test ('ts/src/test/base/test.afterConstructor.ts')) {
            problems.push ('hx10w10 GP24: the seam covers a sliced writer');
        }
    }
    // an import whose text a later rewrite deleted is dropped; a used one stays
    const unusedFile = GP24_HEAD + 'import "strconv"\n\nfunc f (a any) string {\n\treturn ToString(a)\n}\n';
    const unused = hx10w10GP24PruneImports (unusedFile);
    if (unused.includes ('import "strconv"')) {
        problems.push ('hx10w10 GP24: an unused import survived: ' + unused);
    }
    const usedBoth = GP24_HEAD + 'import "strconv"\n\nimport "strings"\n\nfunc f (n int, ids []string) string {\n\treturn strconv.Itoa(n) + "[" + strings.Join(ids, ", ") + "]"\n}\n';
    if (hx10w10GP24PruneImports (usedBoth) !== usedBoth) {
        problems.push ('hx10w10 GP24: a used import was dropped: ' + hx10w10GP24PruneImports (usedBoth));
    }
    const mentioned = GP24_HEAD + 'import "strconv"\n\nfunc f () string {\n\t// strconv.Itoa(n) was here\n\treturn "strconv.Itoa(n)"\n}\n';
    if (hx10w10GP24PruneImports (mentioned).includes ('import "strconv"')) {
        problems.push ('hx10w10 GP24: a comment or literal kept an unused import: ' + hx10w10GP24PruneImports (mentioned));
    }
    const handImport = GP24_HEAD + 'import ccxt "github.com/ccxt/ccxt/go/v4"\n\nfunc f () any {\n\treturn nil\n}\n';
    if (hx10w10GP24PruneImports (handImport) !== handImport) {
        problems.push ('hx10w10 GP24: a non-stdlib import was touched');
    }
    return problems;
}

// the two writers must call the seam (a pass that is never wired changes nothing)
export function hx10w10GP24Wired (): string[] {
    const problems: string[] = [];
    let source = '';
    try {
        source = fs.readFileSync (path.join (process.cwd (), 'build', 'goTranspiler.ts'), 'utf8');
    } catch (e) {
        return problems; // the self-test may run outside the repo root
    }
    if (!source.includes ('hx10w10GP24BaseImports (hx4G20BaseNativePasses (file))')) {
        problems.push ('hx10w10 GP24: transpileBaseMethods does not run the seam');
    }
    if (!source.includes ('hx10w10GP24BaseImports (gp19Pass (')) {
        problems.push ('hx10w10 GP24: transpilePredictionBaseMethods does not run the seam');
    }
    if (!source.includes ('installHx10w10GP24BaseImportSeam (this.transpiler.goTranspiler)')) {
        problems.push ('hx10w10 GP24: setupTranspiler does not install the seam');
    }
    if (!source.includes ('hx10w10GP24PruneImports (content) : content')) {
        problems.push ('hx10w10 GP24: overwriteFileAndFolder does not prune');
    }
    return problems;
}
