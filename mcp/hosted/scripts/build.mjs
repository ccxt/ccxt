#!/usr/bin/env node
// Production build: one self-contained ESM file, dist/server.mjs, with ccxt, the MCP SDK,
// Hono, PostHog and the shared mcp/ts code inlined. The runtime image then needs nothing
// but `node dist/server.mjs` — no node_modules, no source tree, nothing to write.
//
// The MCP Apps views (mcp/ts/ui/*) are read at build time and inlined through a define, so
// the bundle never looks for them on disk; their versioned URIs come out identical to the
// local server's for the same files.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const here = path.dirname (fileURLToPath (import.meta.url));
const root = path.join (here, '..');
const uiDir = path.join (root, '..', 'ts', 'ui');
const pkg = JSON.parse (fs.readFileSync (path.join (root, 'package.json'), 'utf8'));

const assets = {};
for (const file of fs.readdirSync (uiDir).sort ()) {
    if (/^[a-z0-9][a-z0-9.-]*\.(html|css|js)$/.test (file)) {
        assets[file] = fs.readFileSync (path.join (uiDir, file), 'utf8');
    }
}

// a build id the logs and analytics can tell apart: package version plus the git commit
// when the build runs in a checkout (CI and the Docker build pass BUILD_ID instead)
const buildId = process.env.BUILD_ID ?? pkg.version;

const result = await build ({
    'entryPoints': [ path.join (root, 'src', 'main.ts') ],
    'outfile': path.join (root, 'dist', 'server.mjs'),
    'bundle': true,
    'platform': 'node',
    'format': 'esm',
    'target': 'node22',
    'sourcemap': false,
    'minify': false, // stack traces in the logs stay readable; size is dominated by ccxt anyway
    'legalComments': 'eof',
    'metafile': true,
    'logLevel': 'warning',
    'define': {
        '__CCXT_UI_ASSETS__': JSON.stringify (assets),
        '__HOSTED_VERSION__': JSON.stringify (buildId),
        'process.env.NODE_ENV': '"production"',
    },
    // CommonJS dependencies inside an ESM bundle still call require () for node built-ins
    'banner': {
        'js': [
            '// ccxt-mcp-hosted ' + buildId + ' — generated by scripts/build.mjs, do not edit',
            'import { createRequire as __createRequire } from \'node:module\';',
            'const require = __createRequire (import.meta.url);',
        ].join ('\n'),
    },
});

// the reachability check ships in the image too, so it runs from the production machine's
// network with the exact ccxt build the server uses
await build ({
    'entryPoints': [ path.join (root, 'scripts', 'check-exchanges.mjs') ],
    'outfile': path.join (root, 'dist', 'check-exchanges.mjs'),
    'bundle': true,
    'platform': 'node',
    'format': 'esm',
    'target': 'node22',
    'legalComments': 'eof',
    'logLevel': 'warning',
    'banner': {
        'js': 'import { createRequire as __createRequire } from \'node:module\';\nconst require = __createRequire (import.meta.url);',
    },
});

const bytes = fs.statSync (path.join (root, 'dist', 'server.mjs')).size;
const inputs = Object.keys (result.metafile.inputs).length;
console.log ('[build] dist/server.mjs ' + (bytes / 1024 / 1024).toFixed (1) + ' MB from ' + inputs + ' modules, ' + Object.keys (assets).length + ' view assets inlined, build ' + buildId);
